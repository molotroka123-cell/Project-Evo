// render/icons.js — значки состояния над постройками.
//
// ЗАЧЕМ ЭТОТ СЛОЙ. Сейчас единственный способ узнать, что в городе что-то не
// так, — читать журнал. Журнал говорит словами и в прошедшем времени («Цепочка
// «Сталь». Нет шахты»), а карта при этом молчит: кузница без людей, кузница с
// полным складом и кузница, которую вчера разнесло аварией, выглядят одной и
// той же кузницей. Игрок видит падающий выпуск и не знает, КУДА смотреть.
// Этот слой ставит над крышей маленький значок и превращает «где-то что-то
// сломалось» в «вот этот дом».
//
// ЧТО ПОКАЗЫВАЕМ (порядок — он же приоритет, беда важнее стройки):
//   damage  — здание повреждено (b.hp сильно ниже своего максимума)
//   idle    — промысел стоит без рабочих
//   stuck   — цепочка встала (sim.sys.indLinks.flags.bottlenecks)
//   full    — склад полон, добыча пропадает впустую
//   noheir  — у мастера нет ученика: умрёт — ремесло уйдёт с ним
//   build   — идёт стройка
//
// ГРАНИЦЫ. Модуль — чистое представление. Он ЧИТАЕТ sim (buildings, villagers,
// res/resCap, sys.indLinks, linkMasters, world.seed) и не пишет в симуляцию ни
// одного поля. Импорт файла не имеет побочных эффектов: до первого кадра не
// печётся ни одного канваса и не трогается document.
//
// ОДИН ЗНАЧОК НА ПОСТРОЙКУ. Повреждённая кузница без рабочих и с полным складом
// получит ровно один значок — самый тяжёлый из подходящих. Стопка из трёх
// иконок над одной крышей не читается вообще, а игрок всё равно пойдёт чинить
// сначала худшее.
//
// СЛУЧАЙНОСТЬ. Math.random в проекте запрещён, sim.rng рендеру трогать нельзя:
// рендер идёт с разной частотой у разных игроков, и каждый его вызов сдвинул бы
// состояние симуляции — сейв бы поплыл. Единственное, что здесь нужно
// «вразнобой», — фаза покачивания: десяток значков, качающихся строго в такт,
// читается как дрожь экрана, а не как живая карта. Фаза берётся
// детерминированным хешем hash2(seed ^ x, y) из palette.js — тем же приёмом,
// что в water.js / relief.js / vegetation.js.
//
// ЦЕНА КАДРА (оценка; замер за главным разработчиком).
// Стенд для сравнения — тот же, что в docs/visual-performance-budget.md:
// программная растеризация, 1600×900, dpr 1. Каждый кадр слой делает:
//   • ноль работы, если зум мельче порога или значков нет (обычное состояние
//     здорового города: 0–3 значка на весь экран);
