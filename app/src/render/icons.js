export class IconLayer {
  constructor(quality) {
    this.q = quality;
    this.enabled = true;
    this.atlas = null;        // выпечка: 6 ячеек CELL×CELL в ряд
    this.mem = createMemory();
    this.marks = [];
    this.acc = SCAN_SEC;      // первый кадр считает сразу, а не через треть секунды
    this.drawn = 0;
    this.bakes = 0;
  }

  // Пресет меняется — атлас снимаем. Он и правда зависит от пресета: толщина
  // обводки глифа берётся от q.detail, а на eco рисуется упрощённый значок.
  setQuality(q) {
    this.q = q;
    this.atlas = null;
  }

  stats() {
    return { marks: this.marks.length, drawn: this.drawn, bakes: this.bakes, bytes: this.bytes() };
  }
  bytes() { return this.atlas ? this.atlas.width * this.atlas.height * 4 : 0; }

  // Единственный вход из renderer. ox/oy — смещение камеры в пикселях,
  // z — пикселей на клетку, time — this.time рендера (реальные секунды).
  draw(sim, ctx, ox, oy, z, cw, ch, time, dtReal) {
    this.drawn = 0;
    if (!this.enabled || !sim) return;

    // Пересчёт состояния по своему таймеру — до проверки зума, чтобы счётчик
    // простоя не обнулялся, пока игрок смотрит на карту издалека.
    this.acc += dtReal || 0;
    if (this.acc >= SCAN_SEC) {
      this.acc = 0;
      this.marks = scanMarks(sim, this.mem);
    }

    const zoom = z / 32;                       // TILE_PX = 32, см. renderer.js
    if (zoom < minZoomFor(this.q)) return;     // дальний план: молчим
    if (!this.marks.length) return;

    if (!this.atlas) { this.atlas = bakeAtlas(this.q); this.bakes++; }
    const atlas = this.atlas;
    const px = iconPxFor(z);
    const cap = capFor(this.q);
    const seed = (sim.world && sim.world.seed) | 0;

    ctx.save();
    for (let i = 0; i < this.marks.length && this.drawn < cap; i++) {
      const m = this.marks[i];
      const sx = ox + m.x * z;
      // Значок висит над коньком: низ спрайта — это sy + size клеток, высота
      // спрайта — m.top клеток. Ещё 0.55 своего размера сверху — воздух между
      // значком и крышей, иначе он читается как часть постройки.
      const sy = oy + (m.y + m.size - m.top) * z - px * 0.55;
      // Отсечение с запасом в размер значка: половина значка за краем экрана
      // всё равно должна быть видна.
      if (sx < -px || sy < -px || sx > cw + px || sy > ch + px) continue;

      const ph = phaseOf(seed, m.x, m.y);
      const bob = Math.sin(time * BOB_W + ph) * px * BOB_A;
      // Пульс только у тяжёлого повреждения: если мигает всё, не мигает ничто.
      const k = m.kind === 'damage' && m.sev >= 2
        ? 1 + PULSE_A * (0.5 + 0.5 * Math.sin(time * PULSE_W + ph))
        : 1;
      const w = px * k;
      const cell = KIND_IDX[m.kind] * CELL;
      ctx.drawImage(
        atlas, cell, 0, CELL, CELL,
        Math.round(sx - w / 2), Math.round(sy + bob - w / 2), Math.round(w), Math.round(w),
      );
      this.drawn++;
    }
    ctx.restore();
  }
}

