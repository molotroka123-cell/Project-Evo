export function minZoomFor(q) {
  const p = q && q.lod ? q.lod.propsMinZoom : 1;
  return Math.min(p, 1.0);
}

// Потолок значков в кадре. Растёт с детализацией, но не с q.caps.buildings:
// потолок здесь ограничивает не производительность (24 блита — это 0,3 мс), а
// читаемость. Два десятка значков на экране — уже стена, в которой не найти
// главного, и никакой игрок не разгребёт 24 беды за один заход.
export function capFor(q) {
  const d = q && typeof q.detail === 'number' ? q.detail : 1;
  return [12, 18, 24][Math.max(0, Math.min(2, d))];
}

