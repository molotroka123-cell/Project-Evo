//     отсечением за экраном — чистая арифметика,        ~0,004 мс
//   • до CAP_DRAW блитов одной ячейки атласа 56×56 в 14–28 CSS px.
//     Блит масштабирующий (размер значка едет за зумом), поэтому считаем его
//     дороже, чем блит один-в-один: ~0,008–0,014 мс за штуку.
