// Экранный размер значка. Зажат с двух сторон: см. ICON_MIN_PX / ICON_MAX_PX.
export function iconPxFor(z) {
  return Math.max(ICON_MIN_PX, Math.min(ICON_MAX_PX, z * ICON_K));
}

// Фаза покачивания. Детерминированный хеш от сида мира и координат постройки:
// один и тот же город качается одинаково у двух игроков и после загрузки сейва,
// но соседние дома — вразнобой.
export function phaseOf(seed, x, y) {
  return hash2(((seed | 0) ^ Math.round(x * 4)) | 0, Math.round(y * 4)) * 6.2831853;
}

