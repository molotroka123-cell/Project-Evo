// Полная прочность постройки. Ядро ставит hp = def.wall || 100 при закладке
// (simulation.js), и другого источника максимума нет.
export function maxHpOf(def) {
  return (def && def.wall) || 100;
}

// Промысел ли это: есть ли у постройки рабочие места и выпуск. Жильё, стены и
// пассивные здания (treasury, robo_factory с workers: 0) значков «нет рабочих»
// не получают — им рабочие не положены по данным, а не по недосмотру игрока.
export function isCraft(def) {
  return !!(def && def.workers > 0 && def.out && Object.keys(def.out).length);
}

// Полностью ли пропадает выпуск: ВСЕ продукты постройки упёрлись в потолок.
//
// Почему все, а не любой: мануфактура даёт дерево И камень, и когда полон
// только один склад, половина выпуска всё равно идёт в дело — значок «добыча
// пропадает» был бы неправдой. Полный склад одного побочного продукта — обычное
// состояние середины партии, и значок на каждой такой постройке обесценил бы
// весь слой. Золото и знания сюда не попадают никогда: их потолок 99999.
export function outputWasted(def, res, cap) {
  const out = def && def.out;
  if (!out || !res || !cap) return false;
  let any = false;
  for (const r of Object.keys(out)) {
    if (!out[r]) continue;
    const c = cap[r];
    if (!(c > 0) || c >= 99999) return false;   // потолка нет — пропадать нечему
    if ((res[r] || 0) < c * FULL_AT) return false;
    any = true;
  }
  return any;
}

// Кто из построек участвует в какой цепочке. Таблица CHAINS расширяется на ходу
// (registerChain в production.js), поэтому карта пересобирается, когда длина
// таблицы изменилась, а не один раз при импорте: иначе цепочка, добавленная
// модом или сценарием, никогда не получила бы значков.
let _chainLen = -1;
let _chainMap = new Map();
export function chainBuildings() {
  if (CHAINS.length === _chainLen) return _chainMap;
  _chainLen = CHAINS.length;
  _chainMap = new Map();
  for (const c of CHAINS) {
    const set = new Set();
    for (const st of c.stages || []) for (const p of st.by || []) set.add(p.b);
    _chainMap.set(c.id, set);
  }
  return _chainMap;
}

// Память слоя между пересчётами. Отдельным объектом — чтобы тест мог создать
// её руками и прогнать несколько «дней» подряд без канваса и без слоя.
export function createMemory() {
  return {
    day: -1,          // sim.day на прошлом пересчёте
    empty: new WeakMap(), // постройка → сколько игровых дней стоит без рабочих
  };
}

// Сколько игровых дней прошло с прошлого пересчёта.
// Зажимаем в [0, 1]: после загрузки сейва или после «пропущенного века» из
// консоли sim.day прыгает на сотни, и без зажима все пустующие промыслы
// получили бы значок мгновенно, ещё до того, как игрок увидел карту.
function dayStep(sim, mem) {
  const day = sim && typeof sim.day === 'number' ? sim.day : 0;
  const prev = mem.day;
  mem.day = day;
  if (prev < 0) return 0;
  return Math.max(0, Math.min(1, day - prev));
}

// Главный сбор. Возвращает метки в МИРОВЫХ координатах, отсортированные по
// приоритету (тяжёлое первым) и стабильно — по порядку построек в ядре.
// Ни канваса, ни камеры здесь нет намеренно: камера меняется каждый кадр, а
// беды — раз в игровые сутки, и мешать эти два темпа в одной функции значит
// пересчитывать первое со скоростью второго.
export function scanMarks(sim, mem) {
  const marks = [];
  if (!sim || !Array.isArray(sim.buildings)) return marks;
  const dDay = dayStep(sim, mem);

  // 1. Занятые рабочие места. Работники привязаны к постройке через v.target.b
  // при kind === 'work'; b.workers ядро держит ТОЛЬКО для строителей
  // (simulation.js, assignJob) — считать по нему значит не найти ни одного
  // рабочего ни разу. Та же ловушка описана в link_masters.js.
  const staff = new Map();
  for (const v of (sim.villagers || [])) {
    if (!v || (v.hp !== undefined && v.hp <= 0)) continue;
    const t = v.target;
    if (!t || t.kind !== 'work' || !t.b) continue;
    staff.set(t.b, (staff.get(t.b) || 0) + 1);
  }

  // 2. Постройки вставших цепочек. flags.bottlenecks даёт id ЦЕПОЧКИ, а не
  // здания, — сопоставление лежит в CHAINS.
  const stuckIds = new Set();
  const flags = sim.sys && sim.sys.indLinks && sim.sys.indLinks.flags;
  if (flags && Array.isArray(flags.bottlenecks) && flags.bottlenecks.length) {
    const map = chainBuildings();
    for (const row of flags.bottlenecks) {
      const set = row && map.get(row.id);
      if (set) for (const id of set) stuckIds.add(id);
    }
  }
  const stuckLeft = new Map();   // сколько значков ещё можно поставить на id

  // 3. Промыслы, где мастер работает без ученика. crafts в linkMasters
  // ключуются id ПОСТРОЙКИ, но мастер — один человек, и на какой именно из трёх
  // кузниц он стоит, ядро не хранит. Помечаем ровно одну постройку на промысел
  // (первую по порядку в ядре) — иначе одна беда размножилась бы на все кузницы.
  const heirIds = new Set();
  const crafts = sim.linkMasters && sim.linkMasters.crafts;
  if (crafts) {
    for (const [id, c] of Object.entries(crafts)) {
      if (c && c.master && !c.apprentice && c.level >= HEIR_LEVEL) heirIds.add(id);
    }
  }
  const heirUsed = new Set();

  const res = sim.res, cap = sim.resCap;

  for (const b of sim.buildings) {
    if (!b || b.destroyed) continue;
    const def = BUILDINGS[b.id];
    if (!def) continue;                      // здание из мода без описания

    // Счётчик простоя ведём для ВСЕХ промыслов, а не только для тех, что попадут
    // в кадр: иначе он обнулялся бы каждый раз, когда камера отвернулась.
    let emptyDays = 0;
    if (isCraft(def) && b.done) {
      const busy = staff.get(b) || 0;
      emptyDays = busy > 0 ? 0 : (mem.empty.get(b) || 0) + dDay;
      mem.empty.set(b, emptyDays);
    } else if (mem.empty.has(b)) {
      mem.empty.set(b, 0);
    }

    let kind = null, sev = 0;

    if (!b.done) {
      kind = 'build';
    } else {
      const hpK = (b.hp === undefined ? 1 : b.hp) / maxHpOf(def);
      if (hpK < HP_WARN) {
        kind = 'damage';
        // Чем сильнее разрушено, тем выше метка внутри своего вида: когда
        // повреждённых больше потолка, в кадр попадают худшие.
        sev = hpK < HP_SEVERE ? 2 : 1;
      } else if (emptyDays >= EMPTY_GRACE_DAYS) {
        kind = 'idle';
      } else if (stuckIds.has(b.id)) {
        const left = stuckLeft.has(b.id) ? stuckLeft.get(b.id) : MAX_PER_CHAIN;
        if (left > 0) { kind = 'stuck'; stuckLeft.set(b.id, left - 1); }
      }
      if (!kind && outputWasted(def, res, cap)) kind = 'full';
      if (!kind && heirIds.has(b.id) && !heirUsed.has(b.id)) {
        heirUsed.add(b.id);
        kind = 'noheir';
      }
    }
    if (!kind) continue;

    const size = b.size || 1;
    marks.push({
      kind, sev,
      // Центр пятна застройки и высота конька — всё, что нужно кадру.
      x: b.x + size / 2,
      y: b.y,
      size,
      top: Math.min(H_CAP, H_FACTOR * archHeight(ARCH[b.id] || 'house')) * size,
      b,
    });
  }

  // Сортировка один раз здесь, а не в кадре: порядок зависит от состояния мира,
  // а не от камеры, и меняется раз в треть секунды.
  marks.sort((p, q) => {
    const d = weightOf(q) - weightOf(p);
    if (d) return d;
    return p.y - q.y || p.x - q.x;
  });
  if (marks.length > CAP_MARKS) marks.length = CAP_MARKS;
  return marks;
}

// Вес метки: вид плюс тяжесть внутри вида. sev даёт максимум +2, а шаг между
// видами — 10, поэтому тяжёлое повреждение никогда не обгонит вид выше себя.
export function weightOf(m) {
  return ICON_KINDS[KIND_IDX[m.kind]].prio + (m.sev || 0);
}

