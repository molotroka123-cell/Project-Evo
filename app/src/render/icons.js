// ВЫПЕЧКА АТЛАСА
//
// Всё, что стоит дорого, живёт здесь и случается один раз за пресет: тени,
// градиенты дисков, обводки глифов. В кадре от этого остаётся один drawImage.

const TAU = Math.PI * 2;

export function bakeAtlas(q) {
  const detail = q && typeof q.detail === 'number' ? q.detail : 1;
  const cv = document.createElement('canvas');
  cv.width = CELL * ICON_KINDS.length;
  cv.height = CELL;
  const c = cv.getContext('2d');
  for (let i = 0; i < ICON_KINDS.length; i++) {
    c.save();
    c.translate(i * CELL, 0);
    bakeOne(c, ICON_KINDS[i], detail);
    c.restore();
  }
  return cv;
}

function bakeOne(c, kind, detail) {
  const cx = CELL / 2, cy = CELL / 2 - 1;
  // Радиус 20 из 56: остаётся 8 px поля под падающую тень и внешнюю обводку.
  // Без поля тень срезается рамкой ячейки и значок выглядит обрубленным снизу.
  const R = 20;

  // Падающая тень — не blur (он запрещён по цене), а второй диск ниже и темнее.
  // На плоском фоне карты разница неразличима, а стоит она ноль.
  c.fillStyle = 'rgba(0,0,0,0.32)';
  c.beginPath(); c.arc(cx, cy + 2.5, R + 1, 0, TAU); c.fill();

  // Диск. Вертикальный градиент вместо плоской заливки: значок должен читаться
  // объёмной пуговицей и не сливаться с крышей того же тона.
  const g = c.createLinearGradient(0, cy - R, 0, cy + R);
  g.addColorStop(0, mix(kind.color, 255, 0.28));
  g.addColorStop(1, mix(kind.color, 0, 0.22));
  c.fillStyle = g;
  c.beginPath(); c.arc(cx, cy, R, 0, TAU); c.fill();

  // Тёмная обводка — то же средство, что держит силуэт построек в sprites.js:
  // без неё светлый значок пропадает на песке, а тёмный — на воде.
  c.strokeStyle = 'rgba(0,0,0,0.55)';
  c.lineWidth = 2.5;
  c.beginPath(); c.arc(cx, cy, R - 1.2, 0, TAU); c.stroke();

  // Блик по верхней дуге. На eco (detail 0) его нет: на слабом устройстве значок
  // всё равно рисуется в 14–16 px, где блик превращается в грязь на краю.
  if (detail > 0) {
    c.strokeStyle = 'rgba(255,255,255,0.30)';
    c.lineWidth = 2;
    c.beginPath(); c.arc(cx, cy, R - 4, Math.PI * 1.15, Math.PI * 1.85); c.stroke();
  }

  c.save();
  c.translate(cx, cy);
  c.lineCap = 'round';
  c.lineJoin = 'round';
  c.fillStyle = '#fff';
  c.strokeStyle = '#fff';
  (GLYPH[kind.id] || (() => {}))(c);
  c.restore();
}

// Глифы. Все — векторные пути, ни одного fillText.
//
// ПОЧЕМУ НЕ ЭМОДЗИ. Соблазн велик: '⚒', '⚠', '🔨' — одна строка вместо двадцати.
// Но эмодзи рисуется системным шрифтом, и он РАЗНЫЙ на windows, android и mac:
// где-то цветной, где-то контурный, где-то с другой метрикой и другим оптическим
// размером. Значок в 16 px, нарисованный чужим шрифтом, читается как клякса, а
// на части машин не находится вовсе и выпекается квадратом. Плюс это единственная
// вещь в проекте, чей вид зависел бы от машины игрока.
//
// Координаты — от центра диска, в тех же единицах, что радиус R = 20.
const GLYPH = {
  // Трещина: ломаная сверху вниз. Самый узнаваемый знак «сломано» без текста.
  damage(c) {
    c.lineWidth = 4.2;
    c.beginPath();
    c.moveTo(-4.5, -12); c.lineTo(2, -4.5); c.lineTo(-3, 0.5); c.lineTo(3.5, 12);
    c.stroke();
    // Короткая ветка: одна линия читается как молния, ветка делает её трещиной.
    c.lineWidth = 3;
    c.beginPath(); c.moveTo(-3, 0.5); c.lineTo(-8.5, 4.5); c.stroke();
  },

  // Человек под запретом: рабочее место есть, человека нет.
  idle(c) {
    c.beginPath(); c.arc(0, -7.5, 4, 0, TAU); c.fill();
    c.beginPath();
    c.moveTo(-6.5, 9); c.lineTo(-4.5, -1.5); c.lineTo(4.5, -1.5); c.lineTo(6.5, 9);
    c.closePath(); c.fill();
    // Перечёркивание тёмным, а не красным: диск и так жёлтый, красная черта на
    // жёлтом — самое неразборчивое сочетание из возможных.
    c.strokeStyle = 'rgba(40,26,0,0.85)';
    c.lineWidth = 4.5;
    c.beginPath(); c.moveTo(-11, 11); c.lineTo(11, -11); c.stroke();
  },

  // Разорванное звено цепи: две дуги, смотрящие друг на друга, с зазором.
  stuck(c) {
    c.lineWidth = 4;
    c.beginPath(); c.arc(-5.5, 0, 7.5, Math.PI * 0.42, Math.PI * 1.58); c.stroke();
    c.beginPath(); c.arc(5.5, 0, 7.5, Math.PI * 1.42, Math.PI * 0.58); c.stroke();
  },

  // Упёрлось в потолок: стрелка вверх, над ней перекладина.
  full(c) {
    c.fillRect(-11, -13, 22, 3.6);
    c.beginPath();
    c.moveTo(0, -8.5); c.lineTo(7.5, -1); c.lineTo(2.6, -1);
    c.lineTo(2.6, 11.5); c.lineTo(-2.6, 11.5); c.lineTo(-2.6, -1); c.lineTo(-7.5, -1);
    c.closePath(); c.fill();
  },

  // Песочные часы: умение утекает вместе с мастером, передать некому.
  noheir(c) {
    c.fillRect(-9.5, -13, 19, 3.2);
    c.fillRect(-9.5, 9.8, 19, 3.2);
    c.beginPath();
    c.moveTo(-7.5, -9.8); c.lineTo(7.5, -9.8); c.lineTo(0, 0); c.closePath(); c.fill();
    c.beginPath();
    c.moveTo(-7.5, 9.8); c.lineTo(7.5, 9.8); c.lineTo(0, 0); c.closePath(); c.fill();
  },

  // Каска: единственный значок, который НЕ беда. Поэтому и форма мирная, и цвет
  // серо-синий — глаз проходит мимо, пока не начнёт искать стройку намеренно.
  build(c) {
    c.beginPath(); c.arc(0, 2, 9.5, Math.PI, 0); c.closePath(); c.fill();
    c.fillRect(-12.5, 2, 25, 3.6);
    c.fillRect(-2, -9.5, 4, 5);
  },
};

// Смешать hex с чистым каналом (255 — к белому, 0 — к чёрному) на долю k.
// Свой маленький хелпер вместо shade() из palette.js: тот возвращает строку
// 'rgb(...)', а здесь нужны только строки для градиента, и лишний разбор hex
// туда-обратно в выпечке ни к чему.
function mix(hex, to, k) {
  const v = parseInt(hex.slice(1), 16);
  const r = Math.round(((v >> 16) & 255) + (to - ((v >> 16) & 255)) * k);
  const g = Math.round(((v >> 8) & 255) + (to - ((v >> 8) & 255)) * k);
  const b = Math.round((v & 255) + (to - (v & 255)) * k);
  return `rgb(${r},${g},${b})`;
}

