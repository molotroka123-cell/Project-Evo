// Ниже этого зума не рисуем вовсе. Всплывашки переживают жителей: «−2» над
// местом боя — это сообщение, а не украшение, и на общем плане карты оно как
// раз нужнее всего. Но и бесконечно вниз идти нельзя: на зуме 0.3 город
// занимает четверть экрана, и двадцать надписей поверх него — это стена текста
// вместо карты. Берём 60 % от порога видимости жителей: eco 0.60, medium 0.51,
// high 0.42, ultra 0.36. Пресет так и остаётся единственным местом, где записано
// «сколько игра себе позволяет», — своих чисел про зум здесь нет.
export function minZoomFor(q) {
  const p = q && q.lod && typeof q.lod.peopleMinZoom === 'number' ? q.lod.peopleMinZoom : 0.7;
  return p * 0.6;
}

// Потолок надписей В КАДРЕ. Очередь всегда 20 (MAX_LIVE), но на eco экран мельче
// (это телефон), а блит там дороже, поэтому показываем меньше — отсекая, как и
// везде, наименее важное. Привязка к q.detail, а не к q.caps.buildings: потолок
// здесь про читаемость, а не про память.
export function capFor(q) {
  const d = q && typeof q.detail === 'number' ? q.detail : 1;
  return [12, 16, 20][Math.max(0, Math.min(2, d))];
}

// Кегль ВЫПЕЧКИ. Карточка печётся один раз и потом только масштабируется, значит
// печь надо под самый крупный случай, который может понадобиться: MAX_PX
// экранных пикселей, умноженные на плотность холста пресета. На eco (dprCap 1)
// это 26, на medium (1.5) — 39, на high/ultra (2) — 52. Печь мельче — получить
// мыло на ретине; печь крупнее — платить памятью за то, чего не покажут.
// Кегль зависит от пресета, поэтому смена пресета обязана сбросить кэш (см.
// setQuality) — иначе на «ультре» остались бы карточки, испечённые для «эко».
export function bakePxFor(q) {
  const cap = q && typeof q.dprCap === 'number' ? q.dprCap : 1;
  return Math.round(MAX_PX * Math.max(1, Math.min(2, cap)));
}

// Потолки кэша карточек. Десятая часть спрайтового бюджета пресета: карточки
// нужны реже и живут короче, чем здания, и отбирать у зданий память ради
// надписей — плохой размен. eco ≈ 1,0 МБ, medium 1,8, high 3,2, ultra 4,4.
// Записей — не больше, чем пресет разрешает спрайтам: 48/80/120/160.
export function cacheCapsFor(q) {
  const mb = q && q.caps && typeof q.caps.spriteMB === 'number' ? q.caps.spriteMB : 10;
  const n = q && q.caps && typeof q.caps.spriteEntries === 'number' ? q.caps.spriteEntries : 48;
  return { maxBytes: Math.max(0.5, mb * 0.1) * 1024 * 1024, maxEntries: n };
}

