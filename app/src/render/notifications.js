export class Notifications {
  constructor(quality) {
    this.q = quality;
    this.enabled = true;

    // Пул выделен один раз: всплывашки приходят пачками (набег — это десяток
    // событий в один тик), и создавать под каждую объект значило бы кормить
    // сборщик мусора ровно в тот момент, когда на экране и так дым, стрелы и
    // двести жителей. Свободные лежат в free, живые — в live.
    this.pool = [];
    for (let i = 0; i < MAX_LIVE; i++) this.pool.push(newPopup());
    this.free = this.pool.slice();
    this.live = [];
    this.order = [];          // рабочий массив сортировки, тоже без аллокаций

    this.cache = new Map();   // cacheKey → карточка (offscreen-канвас)
    this.seed = 0;            // берётся из sim.world.seed в draw()
    this.serial = 0;          // порядковый номер события — для разброса вбок
    this.drawn = 0;
    this.bakes = 0;
    this.dropped = 0;         // сколько событий не влезло в очередь
  }

  // Пресет меняется — кэш снимаем: кегль выпечки зависит от dprCap (bakePxFor),
  // и карточки от «эко» на «ультре» выглядели бы мылом. Живые всплывашки при
  // этом остаются: они просто перепекутся на следующем кадре.
  setQuality(q) {
    this.q = q;
    this.cache.clear();
  }

  // Новая игра или загрузка сейва: над новым городом не должно висеть «+3🪵»
  // от старого. Кэш карточек при этом не трогаем — строки «+3🪵» и «−2» в
  // следующей партии будут те же самые, и перепекать их незачем.
  clear() {
    for (const p of this.live) this.free.push(p);
    this.live.length = 0;
  }

  stats() {
    return {
      live: this.live.length, drawn: this.drawn, dropped: this.dropped,
      cached: this.cache.size, bakes: this.bakes, bytes: this.bytes(),
    };
  }
  bytes() {
    let n = 0;
    for (const c of this.cache.values()) n += canvasBytes(c.cv);
    return n;
  }

  // ЕДИНСТВЕННЫЙ ВХОД СНАРУЖИ.
  //
  //   x, y  — мировые координаты точки, НАД которой всплывает надпись.
  //           Для постройки передавайте центр пятна: b.x + (b.size||1)/2, b.y —
  //           тогда надпись встанет над коньком, а не над левым нижним углом.
  //           Для жителя — v.x, v.y как есть.
  //   text  — что показать: '+3🪵', '−2', '' (только значок). Длиннее MAX_CHARS
  //           обрезается.
  //   kind  — ключ KINDS: death | combat | disease | birth | full | loss | gain |
  //           info. Неизвестный вид сворачивается к 'info' и не роняет кадр.
  //   up    — необязательная добавка высоты В КЛЕТКАХ. Нужна для высоких
  //           построек: над башней или шпилем надпись, поставленная по b.y,
  //           окажется на середине стены. Считать высоту крыши должен тот, кто
  //           знает архитектуру (sprites.js: ARCH/archHeight), — слой её не
  //           угадывает.
  //
  // Возвращает true, если событие принято, и false, если отброшено по
  // приоритету. Возврат нужен вызывающему, чтобы понимать, что происходит, и
  // тестам — чтобы проверять правило вытеснения.
  push(ev) {
    if (!this.enabled || !ev) return false;
    const x = +ev.x, y = +ev.y;
    if (!Number.isFinite(x) || !Number.isFinite(y)) return false;

    const kind = KINDS[ev.kind] ? ev.kind : DEFAULT_KIND;
    const def = KINDS[kind];
    const prio = typeof ev.prio === 'number' ? ev.prio : def.prio;
    const text = normText(ev.text);

    let p = this.free.pop();
    if (!p) {
      const vi = victimIndex(this.live, prio);
      if (vi < 0) { this.dropped++; return false; }
      p = this.live[vi];
      this.live.splice(vi, 1);
      this.dropped++;
    }

    p.x = x; p.y = y;
    p.up = Number.isFinite(+ev.up) ? +ev.up : 0;
    p.text = text;
    p.kind = kind;
    p.prio = prio;
    p.color = typeof ev.color === 'string' ? ev.color : def.color;
    p.life = def.life;
    p.t = 0;
    p.n = ++this.serial;
    // Стопка считается ОДИН раз, при добавлении: пересчитывать её в кадре
    // значило бы, что надпись прыгает вверх-вниз, пока рядом появляются и
    // умирают соседи.
    p.stack = this._stackAt(x, y);
    this.live.push(p);
    return true;
  }

  // Сколько свежих надписей уже висит над этим же местом. Только свежих: те,
  // что уже поднялись и гаснут, освободили место физически, и загонять новую
  // ещё выше незачем.
  _stackAt(x, y) {
    let n = 0;
    for (const p of this.live) {
      if (p.t > SAME_AGE) continue;
      if (Math.abs(p.x - x) < SAME_SPOT && Math.abs(p.y - y) < SAME_SPOT) n++;
    }
    return Math.min(STACK_MAX, n);
  }

  // Продвижение возрастов. Вынесено из draw() отдельным методом: слой обязан
  // стареть и тогда, когда его не рисуют (зум ушёл на общий план), иначе при
  // возврате камеры игрок увидит залежавшуюся пачку надписей о событиях
  // полуминутной давности.
  update(dtReal) {
    const dt = Math.min(DT_CAP, Math.max(0, dtReal || 0));
    if (!dt || !this.live.length) return;
    // Идём с конца: удаление через splice тогда не сдвигает ещё не пройденные
    // элементы.
    for (let i = this.live.length - 1; i >= 0; i--) {
      const p = this.live[i];
      p.t += dt;
      if (p.t >= p.life) {
        this.live.splice(i, 1);
        this.free.push(p);
      }
    }
  }

  // Вход из renderer. ox/oy — смещение камеры в пикселях, z — пикселей на клетку,
  // cw/ch — размер холста в CSS-пикселях, dtReal — секунды с прошлого кадра.
  draw(sim, ctx, ox, oy, z, cw, ch, dtReal) {
    this.drawn = 0;
    if (sim && sim.world && typeof sim.world.seed === 'number') this.seed = sim.world.seed | 0;
    this.update(dtReal);
    if (!this.enabled || !this.live.length || !ctx) return;

    const zoom = z / 32;                       // TILE_PX = 32, см. renderer.js
    if (zoom < minZoomFor(this.q)) return;     // дальний план: молчим

    const px = pxFor(z);
    const scale = px / bakePxFor(this.q);
    const cap = capFor(this.q);

    // Сортировка по важности ВОЗРАСТАЮЩЕ: важное рисуется последним и потому
    // ложится поверх, а отсекается по потолку — начало списка, то есть самое
    // неважное. Массив order переиспользуется, новых объектов в кадре нет.
    const order = this.order;
    order.length = 0;
    for (const p of this.live) order.push(p);
    order.sort(cmpDrawOrder);
    const from = Math.max(0, order.length - cap);

    let budget = BAKES_PER_FRAME;
    ctx.save();
    for (let i = from; i < order.length; i++) {
      const p = order[i];
      const k = p.t / p.life;

      // Экранная точка якоря считается из МИРОВЫХ координат каждый кадр —
      // поэтому при панораме и зуме надпись остаётся над своим местом, а не
      // плывёт вместе с экраном.
      const jx = (hash2((this.seed ^ p.n) | 0, Math.round(p.x * 8) + Math.round(p.y * 8) * 31) - 0.5) * px * JITTER_K;
      const sx = ox + p.x * z + jx;
      const sy = oy + (p.y - p.up) * z
        - px * AIR_K
        - px * RISE_K * easeRise(k)
        - px * STACK_K * p.stack;

      // Отсечение с запасом в две ширины карточки: половина надписи за краем
      // экрана всё равно должна быть видна.
      if (sx < -cw * 0.25 || sx > cw * 1.25 || sy < -px * 3 || sy > ch + px * 3) continue;

      const key = cacheKey(p.kind, p.text, p.color);
      let card = this.cache.get(key);
      if (card) {
        touch(this.cache, key);
      } else {
        if (budget <= 0) continue;             // печём не больше двух за кадр
        budget--;
        card = this._bake(p);
        if (!card) continue;
      }

      const dw = card.cv.width * scale, dh = card.cv.height * scale;
      ctx.globalAlpha = alphaOf(k);
      // Округление до целых пикселей: карточка и так масштабируется, а дробное
      // смещение добавило бы вторую интерполяцию и размыло обводку.
      ctx.drawImage(card.cv, Math.round(sx - dw / 2), Math.round(sy - dh), Math.round(dw), Math.round(dh));
      this.drawn++;
    }
    ctx.globalAlpha = 1;
    ctx.restore();
  }

  // -------------------------------------------------------------------------
  // ВЫПЕЧКА КАРТОЧКИ
  //
  // Здесь живёт всё дорогое, и случается это один раз на строку: раскладка
  // текста, обводка, вектор значка. В кадре от этого остаётся drawImage.
  _bake(p) {
    if (typeof document === 'undefined' || !document.createElement) return null;
    const font = bakePxFor(this.q);
    const def = kindOf(p.kind);

    const cv = document.createElement('canvas');
    const c = cv.getContext('2d');
    if (!c) return null;

    const fontCss = `bold ${font}px system-ui, "Segoe UI", Roboto, sans-serif`;
    // Обводка толщиной 22 % кегля — то же значение, что у подписей в fx.js.
    // Без неё светлая надпись пропадает на песке, тёмная — на воде; обводка
    // делает карточку читаемой на любом фоне без подложки-плашки, которая
    // закрывала бы саму карту.
    const stroke = Math.max(2, font * 0.22);
    // Поля: половина обводки плюс запас на свесы глифов emoji, которые нередко
    // вылезают за метрики шрифта. Без запаса «🍞» подрезается справа.
    const pad = Math.ceil(stroke * 0.5 + font * 0.14);
    const badge = def.badge ? Math.round(font * 1.05) : 0;
    const gap = badge && p.text ? Math.round(font * 0.22) : 0;

    // measureText есть у любого настоящего контекста; запасной путь нужен
    // подставному контексту в тестах и экзотическим средам без метрик.
    c.font = fontCss;
    const tw = p.text ? (c.measureText ? Math.ceil(c.measureText(p.text).width) : Math.ceil(p.text.length * font * 0.62)) : 0;

    cv.width = Math.max(1, tw + badge + gap + pad * 2);
    // 1.34 кегля — высота строки с запасом на подстрочные элементы и на верхний
    // свес emoji; ниже начинает срезать «🪙».
    cv.height = Math.max(1, Math.ceil(font * 1.34) + pad * 2);

    // Размер канваса сбрасывает контекст — шрифт и настройки ставим ПОСЛЕ.
    c.font = fontCss;
    c.textAlign = 'left';
    c.textBaseline = 'alphabetic';
    c.lineJoin = 'round';
    c.lineCap = 'round';
    c.miterLimit = 2;

    const baseY = pad + Math.round(font * 1.02);
    if (badge) drawBadge(c, def.badge, pad, baseY - font * 0.95, badge, def.color);
    if (p.text) {
      const tx = pad + badge + gap;
      c.lineWidth = stroke;
      c.strokeStyle = 'rgba(12,10,8,0.85)';
      c.strokeText(p.text, tx, baseY);
      c.fillStyle = p.color || def.color;
      c.fillText(p.text, tx, baseY);
    }

    const card = { cv };
    this.cache.set(cacheKey(p.kind, p.text, p.color), card);
    this.bakes++;
    const caps = cacheCapsFor(this.q);
    prune(this.cache, { maxEntries: caps.maxEntries, maxBytes: caps.maxBytes, bytesOf: v => canvasBytes(v.cv) });
    return card;
  }
}

