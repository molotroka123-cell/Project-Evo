function newPopup() {
  return { x: 0, y: 0, up: 0, text: '', kind: DEFAULT_KIND, prio: 0, color: '#fff', t: 0, life: 1, n: 0, stack: 0 };
}

// Порядок вывода: сначала неважное (его же и отсекает потолок), потом важное
// (оно ложится сверху). При равном виде — младшие сверху: свежая надпись должна
// быть читаема, старая уже гаснет.
function cmpDrawOrder(a, b) {
  return (a.prio - b.prio) || (b.t - a.t);
}

// ---------------------------------------------------------------------------
// ЗНАЧКИ
//
// Рисуются векторно, а не символами шрифта. Причина простая: «☠» и «⚔» есть не
// в каждом системном шрифте, и на части машин вместо черепа игрок увидит
// квадрат-заглушку. Вектор выглядит одинаково везде. Каждый значок рисуется в
// единичном квадрате (0..1) и масштабируется под размер карточки; все они
// сначала обводятся тёмным, потом заливаются цветом вида — тот же приём, что у
// текста, и по той же причине: значок обязан читаться и на снегу, и на воде.
function drawBadge(c, id, x, y, s, color) {
  c.save();
  c.translate(x, y);
  c.scale(s, s);
  c.lineWidth = 0.16;
  c.strokeStyle = 'rgba(12,10,8,0.85)';
  c.fillStyle = color;
  const path = BADGES[id];
  if (path) path(c);
  c.restore();
}

// Каждая функция строит путь и сама решает, что обвести и что залить.
// stroke() перед fill() — иначе обводка съедала бы половину фигуры внутрь.
const TAU = Math.PI * 2;

const BADGES = {
  // Череп: свод, скулы, две глазницы, зубы. На 20 px читается именно силуэт
  // «круг с квадратной челюстью», поэтому челюсть намеренно широкая.
  skull(c) {
    c.beginPath();
    c.arc(0.5, 0.42, 0.33, Math.PI, TAU);
    c.lineTo(0.83, 0.52);
    c.lineTo(0.68, 0.62);
    c.lineTo(0.68, 0.80);
    c.lineTo(0.32, 0.80);
    c.lineTo(0.32, 0.62);
    c.lineTo(0.17, 0.52);
    c.closePath();
    c.stroke(); c.fill();
    c.fillStyle = 'rgba(12,10,8,0.85)';
    c.beginPath();
    c.arc(0.37, 0.44, 0.10, 0, TAU);
    c.arc(0.63, 0.44, 0.10, 0, TAU);
    c.rect(0.44, 0.62, 0.12, 0.16);
    c.fill();
  },

  // Скрещённые мечи: два клинка по диагоналям плюс перекрестья. Толщина клинка
  // 0.13 — тоньше уже сливается с обводкой на мелком кегле.
  swords(c) {
    for (const dir of [1, -1]) {
      c.save();
      c.translate(0.5, 0.5);
      c.rotate(dir * Math.PI / 4);
      c.beginPath();
      c.moveTo(-0.065, -0.44);           // остриё
      c.lineTo(0.065, -0.44);
      c.lineTo(0.065, 0.20);
      c.lineTo(-0.065, 0.20);
      c.closePath();
      c.stroke(); c.fill();
      c.beginPath();                     // гарда
      c.rect(-0.20, 0.20, 0.40, 0.09);
      c.stroke(); c.fill();
      c.restore();
    }
  },

  // Болезнь: капля с тремя точками — «зараза», а не медицинский крест.
  // Крест на карте каменного века выглядел бы как больница из другой игры.
  plague(c) {
    c.beginPath();
    c.moveTo(0.5, 0.08);
    c.bezierCurveTo(0.86, 0.46, 0.82, 0.62, 0.72, 0.74);
    c.bezierCurveTo(0.60, 0.90, 0.40, 0.90, 0.28, 0.74);
    c.bezierCurveTo(0.18, 0.62, 0.14, 0.46, 0.5, 0.08);
    c.closePath();
    c.stroke(); c.fill();
    c.fillStyle = 'rgba(12,10,8,0.85)';
    c.beginPath();
    c.arc(0.42, 0.52, 0.075, 0, TAU);
    c.arc(0.62, 0.62, 0.065, 0, TAU);
    c.arc(0.50, 0.72, 0.055, 0, TAU);
    c.fill();
  },

  // Рождение: сердце. Взято не «потому что мило»: на 18–20 px это единственная
  // фигура, которую глаз опознаёт с одного взгляда и не путает ни с чем другим
  // на карте — колыбель и пелёнки на таком размере становятся кляксой.
  heart(c) {
    c.beginPath();
    c.moveTo(0.5, 0.86);
    c.bezierCurveTo(0.06, 0.56, 0.14, 0.14, 0.5, 0.32);
    c.bezierCurveTo(0.86, 0.14, 0.94, 0.56, 0.5, 0.86);
    c.closePath();
    c.stroke(); c.fill();
  },

  // Склад полон: треугольник с восклицательным знаком. Углы скруглены вручную
  // (три дуги), потому что острый угол на 18 px превращается обводкой в кляксу.
  warn(c) {
    const r = 0.09;
    c.beginPath();
    c.moveTo(0.5 - r * 0.5, 0.10 + r * 0.2);
    c.arcTo(0.5, 0.06, 0.5 + r * 0.5, 0.10 + r * 0.2, r);
    c.lineTo(0.92 - r * 0.4, 0.84 - r * 0.5);
    c.arcTo(0.94, 0.88, 0.86, 0.88, r);
    c.lineTo(0.14, 0.88);
    c.arcTo(0.06, 0.88, 0.10, 0.82, r);
    c.closePath();
    c.stroke(); c.fill();
    c.fillStyle = 'rgba(12,10,8,0.85)';
    c.beginPath();
    c.rect(0.44, 0.34, 0.12, 0.28);
    c.rect(0.44, 0.68, 0.12, 0.12);
    c.fill();
  },
};

