// Потолок очереди. Задан не производительностью (20 блитов — это 0,4 мс, см.
// шапку), а читаемостью: два десятка надписей уже закрывают город, и найти
// среди них главную невозможно. Всё, что сверх потолка, отбрасывается по
// приоритету, а не по времени прихода: залп из тридцати «+1🪵» не имеет права
// вытолкнуть единственную смерть.
export const MAX_LIVE = 20;

// Сколько НОВЫХ строк разрешено испечь за один кадр. Одна выпечка — 0,2–0,4 мс;
// три — уже заметная зазубрина на графике кадра. Два — компромисс: первый же
// кадр после набега покажет и «−2», и скрещённые мечи, а остальное подтянется
// в следующие кадры, которых у всплывашки ещё девяносто.
export const BAKES_PER_FRAME = 2;

// Экранный размер надписи (кегль), CSS px. Нижняя граница 12 — предел, ниже
// которого «+12🍞» превращается в грязное пятно; верхняя 26 — предел, выше
// которого надпись начинает спорить с самой постройкой (тайл на зуме 3 — это
// 96 px). Множитель 0.42 выводит на 13,4 px при зуме 1 — то же соотношение,
// с которым живут подписи в fx.js, чтобы два текстовых слоя не выглядели
// набранными разными кеглями.
export const MIN_PX = 12;
export const MAX_PX = 26;
const PX_K = 0.42;

export function pxFor(z) {
  return Math.max(MIN_PX, Math.min(MAX_PX, z * PX_K));
}

// Насколько всплывашка поднимается за свою жизнь — в кегляx, а не в клетках.
// Клетки были бы ошибкой: на зуме 0.5 подъём в 0,9 клетки — это 14 px, надпись
// почти не двигается и читается как приклеенная к крыше; на зуме 3 — 86 px, и
// она улетает в другой конец экрана. Привязка к кеглю даёт один и тот же жест
// на любом зуме: «подняться на полторы своих высоты и растаять».
const RISE_K = 1.7;

// Воздух между якорем и низом надписи, в кеглях. Без него надпись садится
// прямо на голову жителя и читается как часть спрайта.
const AIR_K = 0.55;

// Разброс вбок, в кеглях. 0,5 кегля — примерно ширина цифры: соседние надписи
// перестают ложиться пиксель в пиксель, но продолжают явно указывать на одну
// точку. Больше — и «+1🪵» уедет с лесопилки на соседний дом.
const JITTER_K = 0.5;

// Ступенька стопки, в кеглях. Когда над одним местом висит несколько свежих
// надписей, каждая следующая встаёт на строку выше. 1,15 — межстрочный
// интервал, при котором обводки не слипаются.
const STACK_K = 1.15;

// Глубже трёх стопка не растёт: четвёртая надпись улетела бы за верхний край
// экрана и оторвалась от своего места. Четвёртая и дальше просто лягут поверх
// третьей — они всё равно живут полторы секунды.
const STACK_MAX = 3;

// Радиус «это то же место», в клетках, и возраст, до которого надпись считается
// свежей. 0,75 клетки — чуть меньше тайла: две постройки не могут стоять ближе,
// а житель, отошедший на клетку, уже честно в другом месте.
const SAME_SPOT = 0.75;
const SAME_AGE = 0.6;

// Ограничение длины строки. Всплывашка — не журнал: она обязана читаться
// боковым зрением за долю секунды. 24 литеры — это «+120🪙 подать» с запасом;
// всё, что длиннее, обрежется, и это лучше, чем карточка во весь экран,
// которую придётся печь отдельной строкой кэша.
export const MAX_CHARS = 24;

// Потолок dt, который слой готов принять за один кадр. Игрок свернул вкладку на
