// render/notifications.js — всплывающие числа и знаки над картой.
//
// ЗАЧЕМ ЭТОТ СЛОЙ. Сейчас всё важное уходит в журнал: «Охотник Ждан погиб»,
// «Склад дерева полон», «Набег отбит, потери 2». Журнал — это лента текста
// сбоку, и он отвечает на вопрос «что случилось», но НЕ отвечает на вопрос
// «где». Игрок читает про погибшего охотника и не знает, в каком углу карты
// это было; читает про полный склад и не понимает, какой из четырёх амбаров
// стоит забитым. Слой связывает событие с местом: над постройкой, отдавшей
// добычу, вспыхивает «+3🪵»; над местом боя — «−2» и скрещённые мечи; над
// жителем — знак рождения, смерти или болезни; над полным амбаром — знак беды.
// Через полторы секунды всё это растворяется, и карта снова чистая.
//
// ГРАНИЦЫ. Модуль НИЧЕГО не решает сам. Он не читает sim.villagers, не сравнивает
// sim.res между кадрами, не ищет бои. Он умеет ровно одно: показать то, что ему
// дали через push({x, y, text, kind}). Кто и когда дёргает push — дело
// integrate.js и renderer.js (главный разработчик). Такое разделение выбрано
// нарочно: «догадливый» слой, который сам вычисляет дельты sim.res по кадрам,
// уже был бы вторым, неявным источником правды о хозяйстве — и врал бы при
// первой же паузе, загрузке сейва или прокрутке времени. Единственное, что
// модуль читает из sim, — sim.world.seed, и только ради детерминированного
// разброса (см. ниже).
//
// СЛУЧАЙНОСТЬ. Math.random в проекте запрещён, sim.rng рендеру трогать нельзя:
// рендер идёт с разной частотой у разных игроков, и каждый его вызов сдвинул бы
// состояние симуляции — сейв бы поплыл. Разброс здесь нужен ровно один: боковое
// смещение всплывашки, чтобы три «+1🪵» подряд над одной лесопилкой не легли
// пиксель в пиксель. Он берётся детерминированным хешем hash2(seed ^ serial, …)
// из palette.js — тем же приёмом, что в water.js / relief.js / vegetation.js.
// Одна и та же партия у двух игроков разбрасывает числа одинаково.
//
// ПОЧЕМУ ТЕКСТ ВЫПЕКАЕТСЯ. Наивно — звать ctx.fillText (а с обводкой ещё и
// strokeText) для каждой всплывашки каждый кадр. Раскладка строки с emoji —
// самая дорогая операция Canvas 2D из всех, что здесь встречаются: браузер
// каждый раз заново ищет шрифт для «🪵», строит глифы и растеризует их. На
// двадцати всплывашках при 60 кадрах это 2400 раскладок в секунду ради сорока
// РАЗНЫХ строк за всю партию: «+1🪵», «+3🪵», «−2», «+12🍞» и ещё десяток.
// Поэтому строка печётся в offscreen-канвас ОДИН раз и живёт в LRU-кэше, а в
// кадре остаётся один drawImage. Кэш по строке, а не по всплывашке: сотня
// одинаковых «+1🪵» за партию — это одна выпечка.
//
// ЦЕНА КАДРА (оценка; замер за главным разработчиком).
// Стенд для сравнения — тот же, что в docs/visual-performance-budget.md:
// программная растеризация, 1600×900, dpr 1.
//   • пусто (обычное состояние: событий нет) — один if, 0 мс;
//   • обновление возрастов и отсев умерших: массив не длиннее MAX_LIVE = 20,
//     чистая арифметика,                                        ~0,003 мс;
//   • сортировка по важности перед выводом, ≤20 элементов,      ~0,002 мс;
//   • блиты: до capFor(q) штук (12/16/20 по пресету), каждый — масштабирующий
//     drawImage карточки ~140×50 в 60–120 CSS px плюс запись globalAlpha:
//     ~0,010–0,020 мс за штуку. eco 12 ≈ 0,12–0,24 мс, high/ultra 20 ≈
//     0,20–0,40 мс.
//   ИТОГО худший случай ~0,45 мс — около 2,7 % кадра в 16,6 мс, и только в тот
//   момент, когда на экране одновременно два десятка событий (набег плюс
//   эпидемия). Типовая партия — две-четыре всплывашки, то есть ~0,06 мс.
//
// Выпечка карточки: ~0,2–0,4 мс на НОВУЮ строку (обводка + заливка + вектор
// значка). За партию таких строк десятки, а не тысячи. Чтобы залп из десяти
// новых строк в одном кадре не собрался в 4 мс, на кадр разрешено не больше
// BAKES_PER_FRAME выпечек; не успевшие подождут следующего кадра — всплывашка
