// render/postfx.js — вся пост-обработка кадра одним проходом:
// свечение (bloom), цветокоррекция по времени суток и погоде, виньетка,
// плёночное зерно.
//
// ЗАЧЕМ. Сейчас эти четыре вещи разбросаны по renderer.draw и КАЖДАЯ делает
// свой полноэкранный проход. На кадре 1600×900 это выглядит так:
//
//   заливка тоном времени суток .......... 1 полноэкранная заливка
//   заливка погодным тоном ............... 1 полноэкранная заливка
//   виньетка (блит испечённого градиента)  1 полноэкранный блит
//   зерно (заливка паттерном в 'overlay')  1 полноэкранная заливка, ~8 мс
//   ореолы свечения ...................... по блиту 'lighter' на каждое окно
//
// Четыре полноэкранных прохода — это дороже, чем вся местность вместе с водой
// (§5.2 бюджета: местность 2,5 мс, вся пост-обработка должна укладываться
// в 2,0 мс). Зерно в одиночку стоит 8 мс из 16,6 и делает ultra неиграбельной
// (26,3 FPS, §5.4).
//
// ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ.
//   1. Сливает тон времени суток и тон погоды в ОДНУ заливку. Слияние
//      аналитическое (mergeFills), результат пиксель-в-пиксель тот же, что от
//      двух последовательных — проходов вдвое меньше.
//   2. Свечение собирает в УМЕНЬШЕННЫЙ буфер (сторона делится на q.bloomDiv,
//      площадь — на 25–64) и композитит на экран ОДНИМ блитом по объединяющему
//      прямоугольнику, а не сотней блитов 'lighter' по основному холсту.
//   3. Виньетку печёт один раз на размер окна и блитит 1:1 в пикселях
//      устройства. Хранится ЧЕТВЕРТЬ картинки, три остальные — зеркала.
//   4. Зерно не рисует в кадре вообще. Пресет ultra уже вынес его в поле
//      grainCss — здесь это отдельный CSS-слой поверх канваса, который
//      композитит браузер, и в кадре он стоит ровно ноль.
//
// ---------------------------------------------------------------------------
// ЦЕНА КАДРА — числа, а не обещания.
//
// Все ставки взяты из замеров стенда docs/visual-performance-budget.md §1
// (SwiftShader, растеризация на CPU) и из таблицы в шапке water.js, где те же
// примитивы мерились отдельно. Стенд пессимистичен в 2–4 раза относительно
// машины с настоящей видеокартой; соотношения достоверны везде.
//
//   блит 1:1 без масштаба ............ 0,35 нс на пиксель НАЗНАЧЕНИЯ (0,5 мс на 1,44 Мп)
//   сплошная заливка 'source-over' ... 0,35 нс/px
//   блит с масштабом и сглаживанием .. 4,3  нс/px  (6,2 мс на 1,44 Мп)
//   блит с масштабом без сглаживания . 0,7  нс/px  (1,0 мс на 1,44 Мп)
//   что угодно в режиме 'lighter' .... 6,7  нс/px  (9,7 мс на 1,44 Мп)
//
// Из последней строки следует главное правило файла: 'lighter' по площади
// экрана запрещён. Он в девятнадцать раз дороже обычного наложения, и именно
// поэтому свечение здесь живёт в уменьшенном буфере, а на экран выходит
// одним блитом, режим которого выбирается по площади (см. bloomTier).
//
// Разбор кадра на стенде 1600×900 при dpr 1 (1,44 млн пикселей назначения),
// пресет high, ночной город на 150 построек:
//
//   цветокоррекция: одна заливка вместо двух ......... 0,50 мс  (было 1,00)
//   виньетка: 4 зеркальных блита 1:1, суммарно экран . 0,50 мс  (было 0,50)
//   свечение: очистка буфера 267×150 ................. 0,01 мс
//   свечение: до 96 кисточек внутрь буфера ........... 0,03 мс  (было ~1,00)
//   свечение: один композит по «грязному» прямоугольнику:
//        ярус add  (площадь ≤ 85 тыс. px) ............ ≤ 0,60 мс
//        ярус soft (площадь ≤ 860 тыс. px) ........... ≤ 0,60 мс
//        ярус flat (больше — подъём уходит в заливку) . 0,00 мс
//   зерно ............................................ 0,00 мс  (было 8,00 на ultra)
//   ---------------------------------------------------------------------
//   итого high ....................................... 1,0–1,6 мс из 16,6
//   итого ultra ...................................... 1,1–1,9 мс  (было ~9,5)
//   итого medium (свечения нет) ...................... 1,0 мс
//   итого eco (см. ниже) ............................. 0,5 мс
//
// ЧЕСТНАЯ ОГОВОРКА ПРО DPR. Ставки — на пиксель НАЗНАЧЕНИЯ, а холст на high
// доходит до q.maxCanvasPx = 4,5 млн пикселей (resolveDpr держит именно
// площадь, а не dpr). На потолке площади две полноэкранные операции стоят не
// 1,0, а ~3,1 мс на этом стенде. Это не регресс модуля — это цена ЛЮБОГО
// полноэкранного тонирования; она была и раньше, только проходов было четыре,
// а не два. Считать просто: 0,7 нс × число пикселей холста на два прохода.
//
// ПОЧЕМУ НЕ «НАСТОЯЩИЙ» BLOOM ПО ЯРКОСТИ КАДРА. Классический путь — снять
// кадр в уменьшенный буфер, выжать из него яркое и вернуть обратно. Снять
// можно дёшево (уменьшающий блит в 267×150 — 0,17 мс), но у Canvas 2D нет
// операции «порог», а вернуть результат на экран пришлось бы в 'lighter' по
// ВСЕЙ площади: 1,44 Мп × 6,7 нс = 9,7 мс. Это весь бюджет кадра ради ореолов.
// Поэтому источники света называются явно (note / noteLights) — картинка та же,
// а платим за площадь вокруг ламп, а не за весь экран.
//
// ВЫКЛЮЧЕНИЕ. Три уровня, задаются пресетом:
//   full (medium/high/ultra) — всё вышеописанное;
//   lean (eco) — остаётся ТОЛЬКО слитая тонировка, одна заливка: без неё
//                исчезнет день и ночь, а это не спецэффект, а игровая
//                информация. Одна заливка вместо двух — уже вдвое дешевле;
//   off  — setEnabled(false): draw() не делает ни одной операции. Режим для
//          замера и для «совсем всё выключить»; вместе с эффектами пропадает
//          и суточный тон, поэтому в игре по умолчанию не используется.
//
// СЛУЧАЙНОСТЬ. Ни Math.random, ни sim.rng: рендер идёт с разной частотой у
// разных игроков, и любой вызов rng сдвинул бы состояние симуляции — сейв бы
// поплыл. Здесь свой смеситель hashP от sim.world.seed, как в water.js,
// relief.js, vegetation.js, city_lights.js. Случайность нужна ровно в одном
// месте — плитка зерна, и она обязана быть детерминированной: иначе после
// смены пресета плёнка перерисовалась бы на глазах у игрока.
import { WEATHER_TINT } from './palette.js';
import { BUILDING_ERA_IDX } from '../core/data.js';

// Мировая единица «тайл→экран» при zoom = 1. Дублируется из renderer.js
// намеренно: она не зависит от пресета графики и не экспортируется оттуда,
// а тянуть renderer сюда — кольцевая зависимость.
const TILE_PX = 32;

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

// ---------------------------------------------------------------------------
// Измеренные ставки стенда, МИЛЛИСЕКУНДЫ НА ПИКСЕЛЬ НАЗНАЧЕНИЯ.
// Держатся отдельной таблицей, чтобы costMs() считал предсказание кадра по тем
// же числам, по которым принимаются решения о ярусах, — и чтобы после нового
// замера правилась одна строка, а не десять формул по файлу.
// ---------------------------------------------------------------------------
export const RATE = {
  copy: 0.35e-6,    // блит 1:1 и сплошная заливка 'source-over'
  scaleRough: 0.7e-6, // блит с масштабом, imageSmoothingEnabled = false
  scaleSmooth: 4.3e-6, // то же со сглаживанием — в шесть раз дороже
  add: 7.05e-6,     // масштабный блит без сглаживания в режиме 'lighter'
};

// Сколько миллисекунд слою свечения разрешено потратить на композит.
// Общий бюджет пост-обработки — 2,0 мс (§5.2). Тонировка и виньетка забирают
// по 0,5 мс на стенде, остаток и есть эти числа. На ultra чуть больше:
// ultra и существует ради того, что видно.
const BLOOM_MS = { eco: 0, medium: 0, high: 0.6, ultra: 0.9 };

// Потолок числа кисточек свечения в кадре. При bloomDiv 6 весь город
// умещается в буфер 267×150; после ~96 кисточек с альфой 0,25 каждая
// следующая добавляет пикселю меньше 1/255 — то есть ничего.
const MAX_SPOTS = 96;

// Максимальная непрозрачность виньетки НА КРАЮ испечённой картинки. В кадре
// она домножается на vignetteAlpha() — это бесплатно (globalAlpha), а печь
// отдельную картинку на каждое время суток было бы 5,5 МБ за штуку.
const VIG_MAX = 0.5;

// Хранить четверть виньетки и отражать её три раза или хранить целиком.
// Зеркало — это scale(-1,1) БЕЗ масштабирования, то есть блит остаётся на
// пути 1:1 (0,35 нс/px), а памяти уходит вчетверо меньше: на холсте 4,5 Мп
// это 4,5 МБ против 18 МБ. Бюджет памяти на high — 96 МБ всего, и 18 из них
// за градиент из двух цветов отдавать не за что.
// Если замер когда-нибудь покажет, что зеркальный блит уходит с быстрого пути
// (такое возможно на экзотическом растеризаторе), поставьте здесь false —
// код полного варианта рядом и работает.
const VIG_MIRROR = true;

// Сторона плитки зерна. 96 — как в прежнем drawGrain: меньше даёт видимый
// повтор на 1600 пикселях, больше раздувает data-URL (плитка уходит в CSS
// строкой base64, 96×96 — это ~25 КБ, 192×192 было бы ~100 КБ).
const GRAIN_TILE = 96;

// ---------------------------------------------------------------------------
// Смеситель для детерминированного шума. Тот же, что palette.hash2, но с сидом
// мира и солью: одна и та же плитка зерна в одном и том же мире всегда
// одинакова, а разные свойства не коррелируют между собой.
// ---------------------------------------------------------------------------
export function hashP(seed, x, y, salt) {
  let h = (x * 374761393 + y * 668265263 + seed * 1442695041 + salt * 2246822519) | 0;
  h = (h ^ (h >>> 13)) * 1274126177 | 0;
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

// ---------------------------------------------------------------------------
// Аналитическое слияние последовательных полупрозрачных заливок.
//
// Две заливки подряд дают на базовом цвете c0:
//   c = c0·(1−a1)(1−a2) + [c1·a1·(1−a2) + c2·a2]
// Одна заливка (C, A) даёт c = c0·(1−A) + C·A. Приравнивая:
//   A = 1 − Π(1−ai),  C = S / A,  где S копится по правилу S ← S·(1−a) + c·a.
// Это ТОЧНОЕ равенство, а не приближение: картинка не меняется, проход исчезает.
//
// Принимает массив [r, g, b, a]; возвращает {r, g, b, a} с целыми компонентами
// (canvas всё равно квантует в байт, а строка вида 'rgba(12.7,…)' валидна, но
// заставляет парсер работать с плавающей точкой каждый кадр).
// ---------------------------------------------------------------------------
export function mergeFills(list) {
  let keep = 1, r = 0, g = 0, b = 0;
  for (const f of list) {
    if (!f) continue;
    const a = clamp01(f[3]);
    if (!(a > 0)) continue;
    r = r * (1 - a) + f[0] * a;
    g = g * (1 - a) + f[1] * a;
    b = b * (1 - a) + f[2] * a;
    keep *= (1 - a);
  }
  const A = 1 - keep;
  if (A <= 0) return { r: 0, g: 0, b: 0, a: 0 };
  return {
    r: Math.round(clamp01(r / A / 255) * 255),
    g: Math.round(clamp01(g / A / 255) * 255),
    b: Math.round(clamp01(b / A / 255) * 255),
    a: A,
  };
}

// ---------------------------------------------------------------------------
// Итоговый цвет цветокоррекции кадра.
//
// Складываются три вещи:
//   1. тон времени суток (palette.lightAt().tint) — он и делает ночь ночью;
//   2. погодный тон (palette.WEATHER_TINT) — дождь, гроза, снег, туман, зной;
//   3. приближение обесцвечивания.
//
// Про пункт 3 честно. Настоящее обесцвечивание — это операция над яркостью
// каждого пикселя; на Canvas 2D она делается либо getImageData (десятки
// миллисекунд), либо отдельным полноэкранным проходом в режиме 'saturation'
// (то есть ещё 6,7 нс/px, см. таблицу в шапке). Обе цены недопустимы ради
// эффекта, который зритель читает как «краски сели». Серая вуаль малой
// непрозрачности тянет все цвета к одному серому — не то же самое
// математически, но глазами неотличимо, а стоит НОЛЬ: она вливается в ту же
// единственную заливку. Коэффициент 0,13 подобран так, чтобы туман (desat
// 0,50) давал вуаль 0,065 — на глаз это ровно та же потеря цвета, что даёт
// честный фильтр saturate(0,5) поверх уже затонированного кадра.
//
// q.saturation (ultra) вуаль гасит: пресет обещает более сочную картинку, и
// добавлять к ней серого — прямое противоречие.
// ---------------------------------------------------------------------------
export function gradeFor(L, weather, q, lift) {
  const fills = [];
  if (L && L.tint && L.tint[3] > 0.004) fills.push(L.tint);
  const w = WEATHER_TINT[weather];
  if (w && w.tint[3] > 0.004) fills.push(w.tint);
  const desat = w ? (w.desat || 0) : 0;
  if (desat > 0 && !(q && q.saturation)) fills.push([150, 152, 156, desat * 0.13]);
  // Равномерный подъём от свечения — только когда ореолы залили весь экран и
  // отдельный блит потерял смысл (ярус flat, см. bloomTier).
  if (lift && lift.a > 0.002) fills.push([lift.r, lift.g, lift.b, lift.a]);
  return mergeFills(fills);
}

// Сила виньетки в кадре: множитель к испечённой картинке.
// Днём кадр открытый, ночью собранный — 0,62 против 1,0. Это не вкусовщина:
// при ярком дне тёмные углы читаются как грязь на экране, а ночью ровно та же
// картинка читается как «свет только в городе». В непогоду сжимаем ещё чуть
// сильнее — туман и гроза и так съедают периферию.
export function vignetteAlpha(L, weather) {
  const night = L ? clamp01(L.glow) : 0;
  let k = 0.62 + 0.38 * night;
  const w = WEATHER_TINT[weather];
  if (w) k *= 1 + 0.22 * (w.desat || 0);
  return clamp01(k);
}

// ---------------------------------------------------------------------------
// Выбор яруса композита свечения по площади «грязного» прямоугольника.
//
//   add  — 'lighter'. Единственный режим, дающий настоящий пересвет: ореол
//          прибавляется к кадру и может выбить его в белое. Стоит 7,05 нс/px,
//          поэтому разрешён только на маленькой площади. Это ровно тот случай,
//          когда он и нужен: три костра в темноте.
//   soft — 'source-over' с пониженной альфой. Пересвета нет, ореол есть,
//          цена 0,7 нс/px — в десять раз дешевле. Ночной город целиком.
//   flat — ореолы залили всё, отдельный блит стал бы просто «подсветить экран
//          равномерно». Именно это и делаем — но не блитом, а прибавкой к
//          заливке цветокоррекции, которая всё равно рисуется. Ноль работы.
//   off  — светить нечем.
//
// Пороги считаются из бюджета делением на ставку, а не задаются числом: если
// bloomMs поменяют, пороги переедут сами и останутся согласованными.
// ---------------------------------------------------------------------------
export function bloomTier(areaPx, bloomMs) {
  if (!(areaPx > 0) || !(bloomMs > 0)) return 'off';
  if (areaPx <= bloomMs / RATE.add) return 'add';
  if (areaPx <= bloomMs / RATE.scaleRough) return 'soft';
  return 'flat';
}

// ===========================================================================
export class PostFX {
  constructor(quality) {
    this.q = quality;
    this.enabled = true;

    // Геометрия кадра — В ПИКСЕЛЯХ УСТРОЙСТВА. Весь модуль работает именно в
    // них: renderer держит на контексте transform = dpr, и если печь виньетку
    // в CSS-пикселях, а блитить под этим transform, получится МАСШТАБНЫЙ блит
    // (4,3 нс/px вместо 0,35 — на холсте 4,5 Мп это 19 мс вместо 1,6).
    // Поэтому draw() сбрасывает transform в единицу и рисует 1:1.
    this.W = 0; this.H = 0; this.dpr = 1;

    this.on = false;        // работает ли слой в этом кадре
    this.lean = false;      // eco: только тонировка
    this.grade = { r: 0, g: 0, b: 0, a: 0 };
    this.vigK = 0;

    // Буфер свечения.
    this.buf = null; this.bctx = null;
    // bufOn — «буфер свечения жив В ЭТОМ кадре». Отдельный флаг, а не проверка
    // this.buf: после смены пресета на medium канвас остаётся выделенным (его
    // жалко выбрасывать — авто-тюнер ходит туда-сюда), но писать в него и тем
    // более композитить его на экран нельзя.
    this.bufOn = false;
    this.bw = 0; this.bh = 0; this.div = 6;
    this.dirty = { x0: 0, y0: 0, x1: -1, y1: -1 };
    this.spots = 0; this.dropped = 0;
    this.tier = 'off';
    this.liftW = 0; this.liftC = 0;

    // Выпечка: кисти ореола и виньетка.
    this.brushWarm = null; this.brushCold = null;
    this.vig = null; this.vigW = 0; this.vigH = 0; this.vigSoft = false;
    this.vigQW = 0; this.vigQH = 0;

    // CSS-слой зерна.
    this.grainEl = null; this.grainStyle = null;
    this.grainSeed = null; this.grainTried = false;

    this.lastCost = 0;
  }

  // Смена пресета. Выбрасывается только то, что от пресета зависит:
  // буфер свечения (его сторона задана bloomDiv) и виньетка (softLight
  // подмешивает в неё тёплый подъём). Кисти ореола от пресета не зависят.
  setQuality(q) {
    if (!q || q === this.q) { this.q = q || this.q; return; }
    const divChanged = q.bloomDiv !== this.q.bloomDiv;
    const softChanged = !!q.softLight !== !!this.q.softLight;
    this.q = q;
    if (divChanged) { this.buf = null; this.bctx = null; this.bw = this.bh = 0; }
    if (softChanged) this.vig = null;
    this.syncGrain();
  }

  setEnabled(v) { this.enabled = !!v; }

  // -------------------------------------------------------------------------
  // Начало кадра. Вызывается ОДИН раз, до всех note().
  //
  // opts: { dpr, ox, oy, z, zoom, time }. Если переданы ox/oy/z — слой сам
  // соберёт огни города (noteLights); отдельного вызова не нужно.
  // -------------------------------------------------------------------------
  begin(sim, cw, ch, L, opts = {}) {
    const q = this.q;
    this.on = false;
    this.lean = false;
    this.tier = 'off';
    this.spots = 0; this.dropped = 0;
    this.bufOn = false;
    this.liftW = 0; this.liftC = 0;
    this.dirty.x1 = -1; this.dirty.y1 = -1;
    this.lastCost = 0;
    if (!this.enabled || !q) return;

    const dpr = opts.dpr > 0 ? opts.dpr : 1;
    this.dpr = dpr;
    this.W = Math.max(1, Math.round(cw * dpr));
    this.H = Math.max(1, Math.round(ch * dpr));
    this.weather = sim ? sim.weather : null;
    this.L = L;

    // eco: ни виньетки, ни свечения, ни зерна — остаётся суточный тон.
    this.lean = !q.vignette && !q.bloom;
    this.on = true;

    this.vigK = q.vignette ? vignetteAlpha(L, this.weather) : 0;

    // Буфер свечения. clearRect по 40 тыс. пикселей — 0,01 мс; пересоздание
    // канваса стоит на два порядка больше, поэтому размер меняется только при
    // resize и при смене пресета.
    if (q.bloom && (BLOOM_MS[q.id] || 0) > 0) {
      this.div = Math.max(2, q.bloomDiv | 0 || 6);
      const bw = Math.max(8, Math.ceil(this.W / this.div));
      const bh = Math.max(8, Math.ceil(this.H / this.div));
      if (!this.buf || this.bw !== bw || this.bh !== bh) {
        const cv = makeCanvas(bw, bh);
        if (cv) {
          this.buf = cv; this.bctx = cv.getContext('2d');
          this.bw = bw; this.bh = bh;
        }
      }
      if (this.bctx) {
        this.bufOn = true;
        this.bctx.setTransform(1, 0, 0, 1, 0, 0);
        this.bctx.clearRect(0, 0, this.bw, this.bh);
        this.bctx.globalCompositeOperation = 'lighter';
        // Внутри буфера 'lighter' бесплатен: 40 тыс. пикселей против 1,44 млн
        // на экране. Правило «lighter только в выпечке» — то же, что в water.js.
      }
    }

    if (typeof opts.z === 'number' && opts.z > 0) {
      this.noteLights(sim, opts.ox || 0, opts.oy || 0, opts.z, cw, ch, L);
    }

    this.ensureGrain();
  }

  // -------------------------------------------------------------------------
  // Заявка на яркое место. Координаты — В CSS-ПИКСЕЛЯХ КАДРА, то есть ровно те
  // же dx, dy, dw, dh, которыми renderer блитит спрайт: вызывающему не нужно
  // знать ни про dpr, ни про делитель буфера.
  //
  // warm: тёплый источник (огонь, лампа) против холодного (неон, Шпиль).
  // k: сила, 0..1.
  // Возвращает false, когда потолок кисточек исчерпан, — по этому можно
  // прервать обход, а не крутить цикл впустую.
  // -------------------------------------------------------------------------
  note(x, y, w, h, warm, k) {
    if (!this.on || !this.bufOn || !this.bctx) return false;
    if (this.spots >= MAX_SPOTS) { this.dropped++; return false; }
    if (!(w > 0) || !(h > 0) || !(k > 0)) return true;   // вырожденная заявка — молча мимо
    if (!isFinite(x) || !isFinite(y)) return true;

    const d = this.dpr / this.div;
    // Центр ореола — не центр спрайта: свет живёт в верхних двух третях
    // постройки (окна, горн, костёр у стены), а не в геометрическом центре.
    const cx = (x + w * 0.5) * d;
    const cy = (y + h * 0.45) * d;
    // Радиус ореола — 0,8 ширины спрайта. Меньше — ореол не выходит за силуэт
    // и его не видно вообще; больше — город превращается в одно пятно.
    const r = Math.max(1.5, w * 0.8 * d);
    if (cx + r < 0 || cy + r < 0 || cx - r > this.bw || cy - r > this.bh) return true;

    const brush = warm ? this.warmBrush() : this.coldBrush();
    if (!brush) return true;
    const a = clamp01(k);
    this.bctx.globalAlpha = a;
    this.bctx.drawImage(brush, cx - r, cy - r, r * 2, r * 2);
    this.spots++;

    // Границы «грязного» прямоугольника — по ним считается площадь композита.
    const d0 = this.dirty;
    const x0 = cx - r, y0 = cy - r, x1 = cx + r, y1 = cy + r;
    if (d0.x1 < d0.x0) { d0.x0 = x0; d0.y0 = y0; d0.x1 = x1; d0.y1 = y1; }
    else {
      if (x0 < d0.x0) d0.x0 = x0;
      if (y0 < d0.y0) d0.y0 = y0;
      if (x1 > d0.x1) d0.x1 = x1;
      if (y1 > d0.y1) d0.y1 = y1;
    }

    // Копим равномерную составляющую на случай яруса flat. Считаем долю
    // экрана, которую занял ореол, — это и есть его вклад в средний подъём.
    const frac = (r * r * 4) / (this.bw * this.bh);
    if (warm) this.liftW += frac * a; else this.liftC += frac * a;
    return true;
  }

  // Сбор огней города своими силами — чтобы подключение стоило renderer'у
  // одной строки, а не правок внутри drawBuilding.
  noteLights(sim, ox, oy, z, cw, ch, L) {
    if (!this.on || !this.bufOn || !this.bctx || !sim || !sim.buildings) return 0;
    const glow = L ? L.glow : 0;
    if (glow < 0.05) return 0;                 // днём светиться нечему
    const zoom = z / TILE_PX;
    // Ниже порога свечения окон постройки уже не рисуют свет — ореолу неоткуда
    // взяться. Коэффициент 0,7: на дальнем зуме толпа заменяется общим пятном,
    // и мягкий ореол над кварталом там как раз к месту.
    if (zoom < (this.q.lod.buildingGlowMinZoom || 0) * 0.7) return 0;

    let n = 0;
    for (const b of sim.buildings) {
      if (b.destroyed || b.done === false) continue;
      const size = (b.size || 1) * z;
      const sx = ox + b.x * z, sy = oy + b.y * z;
      if (sx < -size * 2 || sy < -size * 3 || sx > cw + size * 2 || sy > ch + size * 2) continue;
      const era = BUILDING_ERA_IDX[b.id] || 0;
      // Граница тёплых и холодных эпох — 7: с «современности» ERA_PALETTE.glow
      // уже голубой, и тёплый ореол над таким домом читается как чужая лампа.
      // Сила 0,26: ореол должен угадываться, а не спорить с самими окнами,
      // которые рисует city_lights/renderer поверх фасада.
      if (!this.note(sx, sy - size * 0.35, size, size, era < 7, glow * 0.26)) break;
      n++;
    }
    return n;
  }

  // -------------------------------------------------------------------------
  // Единственный проход по экрану.
  //
  // Порядок внутри прохода: цветокоррекция → свечение → виньетка.
  // Он не случаен. Если положить свечение ПОД тонировку, ночной тон (альфа до
  // 0,46) съест ореолы наполовину, и лампы ночью будут тусклее, чем днём, —
  // ровно наоборот тому, что нужно. Виньетка идёт последней: она обязана
  // гасить и ореолы тоже, иначе свет у края экрана выглядит приклеенным.
  // -------------------------------------------------------------------------
  draw(ctx) {
    if (!this.on || !ctx) return;
    const W = this.W, H = this.H;

    // Площадь композита свечения и ярус — считаются здесь, потому что до
    // конца кадра ещё могли прийти заявки из fx.js.
    const d = this.dirty;
    let area = 0, sx0 = 0, sy0 = 0, sw = 0, sh = 0;
    if (this.bufOn && d.x1 >= d.x0 && this.buf) {
      sx0 = Math.max(0, Math.floor(d.x0));
      sy0 = Math.max(0, Math.floor(d.y0));
      sw = Math.min(this.bw, Math.ceil(d.x1)) - sx0;
      sh = Math.min(this.bh, Math.ceil(d.y1)) - sy0;
      if (sw > 0 && sh > 0) area = sw * sh * this.div * this.div;
    }
    this.tier = bloomTier(area, BLOOM_MS[this.q.id] || 0);

    // Ярус flat: подъём вливается в заливку цветокоррекции. Потолок 0,05 —
    // выше кадр начинает выглядеть засвеченным туманом, а не подсвеченным.
    let lift = null;
    if (this.tier === 'flat') {
      const total = this.liftW + this.liftC;
      const a = Math.min(0.05, total * 0.35);
      if (a > 0.002) {
        const warmK = total > 0 ? this.liftW / total : 1;
        lift = {
          r: Math.round(140 + 115 * warmK),
          g: Math.round(190 + 20 * warmK),
          b: Math.round(230 - 100 * warmK),
          a,
        };
      }
    }
    const grade = gradeFor(this.L, this.weather, this.q, lift);
    this.grade = grade;

    ctx.save();
    // 1:1 в пикселях устройства — единственный дешёвый режим полноэкранных
    // операций. Всё, что нарисовано ниже, измеряется в них же.
    if (ctx.setTransform) ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.globalCompositeOperation = 'source-over';
    ctx.globalAlpha = 1;

    let cost = 0;

    // --- 1. цветокоррекция: одна заливка вместо двух ---
    if (grade.a > 0.004) {
      ctx.fillStyle = `rgba(${grade.r},${grade.g},${grade.b},${grade.a.toFixed(3)})`;
      ctx.fillRect(0, 0, W, H);
      cost += W * H * RATE.copy;
    }

    // --- 2. свечение: один блит по «грязному» прямоугольнику ---
    if ((this.tier === 'add' || this.tier === 'soft') && area > 0) {
      // Сглаживание при увеличении выключено намеренно. Оно стоит 4,3 нс/px
      // против 0,7 — вшестеро, — а сохранять ему тут нечего: в буфере лежат
      // только мягкие радиальные градиенты без единого резкого края (кисть
      // печётся именно такой, см. bakeBrush). Ступеньки увеличения ×5..×8
      // видны на резком контуре; на пологом склоне их нет.
      if ('imageSmoothingEnabled' in ctx) ctx.imageSmoothingEnabled = false;
      if (this.tier === 'add') {
        ctx.globalCompositeOperation = 'lighter';
        ctx.globalAlpha = 1;
        cost += area * RATE.add;
      } else {
        // 'source-over' пересвета не даёт, поэтому альфу приходится держать
        // выше, чем при 'lighter', иначе ореол исчезает: 0,62 подобрано так,
        // чтобы переход между ярусами при панораме не бросался в глаза.
        ctx.globalCompositeOperation = 'source-over';
        ctx.globalAlpha = 0.62;
        cost += area * RATE.scaleRough;
      }
      ctx.drawImage(
        this.buf, sx0, sy0, sw, sh,
        sx0 * this.div, sy0 * this.div, sw * this.div, sh * this.div,
      );
      ctx.globalCompositeOperation = 'source-over';
      ctx.globalAlpha = 1;
      if ('imageSmoothingEnabled' in ctx) ctx.imageSmoothingEnabled = true;
    }

    // --- 3. виньетка: испечённая четверть, отражённая три раза ---
    if (this.vigK > 0.01) {
      this.ensureVignette(W, H);
      if (this.vig) {
        ctx.globalAlpha = this.vigK;
        this.blitVignette(ctx, W, H);
        ctx.globalAlpha = 1;
        cost += W * H * RATE.copy;
      }
    }

    ctx.restore();
    this.lastCost = cost;
  }

  // Предсказание цены последнего кадра в миллисекундах по ставкам стенда.
  // Нужно не для красоты: главный разработчик сможет сверить предсказание с
  // настоящим замером и понять, где модель врёт, — а не гадать, куда ушло время.
  costMs() { return this.lastCost; }

  stats() {
    return {
      on: this.on, lean: this.lean, tier: this.tier,
      spots: this.spots, dropped: this.dropped,
      w: this.W, h: this.H, div: this.div,
      bufPx: this.buf ? this.bw * this.bh : 0,
      vigPx: this.vig ? this.vigQW * this.vigQH : 0,
      grade: this.grade, vigK: +this.vigK.toFixed(3),
      grain: !!this.grainEl,
      costMs: +this.lastCost.toFixed(3),
    };
  }

  // -------------------------------------------------------------------------
  // Выпечка кисти ореола.
  //
  // 64 пикселя стороны хватает с запасом: в буфере при bloomDiv 6 постройка в
  // один тайл занимает 32·1,6/6 ≈ 9 пикселей, то есть кисть всегда ужимается.
  // Ужатие прощает всё, растяжение делает из ореола кляксу.
  //
  // Профиль альфы пологий на всём протяжении (0,55 → 0,26 → 0,08 → 0) — это и
  // есть причина, по которой композит можно делать без сглаживания. Кисть с
  // ярким плотным ядром дала бы при увеличении ×6 видимые квадраты.
  // -------------------------------------------------------------------------
  warmBrush() {
    if (!this.brushWarm) this.brushWarm = bakeBrush('255,196,110');
    return this.brushWarm;
  }
  coldBrush() {
    if (!this.brushCold) this.brushCold = bakeBrush('150,215,255');
    return this.brushCold;
  }

  // -------------------------------------------------------------------------
  // Выпечка виньетки. Печётся ЧЕТВЕРТЬ: картинка симметрична относительно обеих
  // осей, а память на холсте 4,5 Мп — 4,5 МБ против 18 МБ.
  //
  // Градиент задаётся в координатах ПОЛНОГО кадра, а рисуется в прямоугольник
  // четверти; центр (W/2, H/2) приходится ровно на её дальний угол.
  // -------------------------------------------------------------------------
  ensureVignette(W, H) {
    const soft = !!this.q.softLight;
    if (this.vig && this.vigW === W && this.vigH === H && this.vigSoft === soft) return;
    const qw = VIG_MIRROR ? Math.ceil(W / 2) : W;
    const qh = VIG_MIRROR ? Math.ceil(H / 2) : H;
    const cv = makeCanvas(qw, qh);
    if (!cv) return;
    const c = cv.getContext('2d');
    const cx = W / 2, cy = H / 2;

    // Мягкий свет (ultra) — не отдельный проход, а тёплая вуаль, впечённая в ту
    // же картинку. Отдельный проход в режиме 'soft-light' стоил бы ещё 6,7 нс
    // на пиксель экрана; здесь он стоит ноль, платой служит только то, что его
    // сила привязана к силе виньетки (обе домножаются на один globalAlpha).
    if (soft) {
      const gl = c.createRadialGradient(cx, cy, 0, cx, cy, Math.min(W, H) * 0.55);
      gl.addColorStop(0, 'rgba(255,226,182,0.055)');
      gl.addColorStop(0.7, 'rgba(255,226,182,0.014)');
      gl.addColorStop(1, 'rgba(255,226,182,0)');
      c.fillStyle = gl;
      c.fillRect(0, 0, qw, qh);
    }

    // r0 — радиус полной прозрачности. 0,34 от меньшей стороны: город обычно
    // держат в центре, и затемнять его виньеткой нельзя.
    // r1 — 0,60 диагонали: угол кадра оказывается чуть дальше края градиента,
    // то есть углы получают полную силу, а не 90 % от неё.
    const g = c.createRadialGradient(cx, cy, Math.min(W, H) * 0.34, cx, cy, Math.hypot(W, H) * 0.60);
    g.addColorStop(0, 'rgba(0,0,0,0)');
    g.addColorStop(0.55, `rgba(0,0,0,${(VIG_MAX * 0.18).toFixed(3)})`);
    g.addColorStop(1, `rgba(0,0,0,${VIG_MAX})`);
    c.fillStyle = g;
    c.fillRect(0, 0, qw, qh);

    this.vig = cv; this.vigW = W; this.vigH = H; this.vigSoft = soft;
    this.vigQW = qw; this.vigQH = qh;
  }

  // Четыре блита 1:1 вместо одного — суммарно те же W·H пикселей назначения.
  // Зеркала берут срез шириной ровно W−qw, поэтому по центральной линии нет
  // перекрытия: перекрытие полупрозрачной картинки дало бы тёмный крест.
  blitVignette(ctx, W, H) {
    const cv = this.vig, qw = this.vigQW, qh = this.vigQH;
    if (!VIG_MIRROR) { ctx.drawImage(cv, 0, 0, W, H); return; }
    const rw = W - qw, rh = H - qh;
    ctx.drawImage(cv, 0, 0, qw, qh, 0, 0, qw, qh);
    if (rw > 0) {
      ctx.save(); ctx.translate(W, 0); ctx.scale(-1, 1);
      ctx.drawImage(cv, 0, 0, rw, qh, 0, 0, rw, qh); ctx.restore();
    }
    if (rh > 0) {
      ctx.save(); ctx.translate(0, H); ctx.scale(1, -1);
      ctx.drawImage(cv, 0, 0, qw, rh, 0, 0, qw, rh); ctx.restore();
    }
    if (rw > 0 && rh > 0) {
      ctx.save(); ctx.translate(W, H); ctx.scale(-1, -1);
      ctx.drawImage(cv, 0, 0, rw, rh, 0, 0, rw, rh); ctx.restore();
    }
  }

  // -------------------------------------------------------------------------
  // ЗЕРНО — CSS-слой поверх канваса, а не рисование в кадре.
  //
  // Прежний путь: полноэкранная заливка паттерном в режиме 'overlay' каждый
  // кадр — 8 мс из 16,6 ради эффекта прозрачностью 3 % (§5.4 бюджета).
  // Здесь плитка шума уходит в data-URL, слой лежит отдельным элементом с
  // mix-blend-mode: overlay, и его композитит браузер — в кадре игры ноль
  // работы, ноль обращений к канвасу.
  //
  // Слой ставится под HUD: у канваса #game z-index не задан (то есть 0), у
  // панелей HUD — 15 и выше. z-index: 1 попадает ровно между ними, и зерно
  // ложится на картинку, но не на текст интерфейса.
  //
  // Движение зерна — сдвиг фона по ключевым кадрам, четыре положения со
  // взаимно непохожими смещениями (37/11, 61/73, 17/53 — числа взаимно простые
  // с 96, чтобы плитка не «щёлкала» обратно в исходное положение). Шаговая
  // функция steps(1) даёт именно щелчок плёнки, а не плавное сползание.
  // Длительность = 4 / grainFps: пресет просит 8 кадров в секунду, значит цикл
  // из четырёх положений длится полсекунды.
  // -------------------------------------------------------------------------
  ensureGrain() {
    const want = (this.q && this.q.grainCss > 0) ? this.q.grainCss : 0;
    if (this.grainEl) { this.syncGrain(); return; }
    if (!want || this.grainTried) return;
    this.grainTried = true;                    // одна попытка: DOM либо есть, либо нет
    if (typeof document === 'undefined' || !document.body || !document.createElement) return;

    const seed = 0x9e37;                        // сид плитки: от мира не зависит,
    // плёнка — свойство камеры, а не карты; зато фиксирован, чтобы одна и та же
    // сборка всегда давала одну и ту же плёнку.
    const url = grainDataUrl(seed);
    if (!url) return;

    const fps = (this.q && this.q.grainFps) || 8;
    const dur = (4 / fps).toFixed(3);
    const style = document.createElement('style');
    style.textContent =
      '@keyframes frontier-grain{' +
      '0%{background-position:0 0}' +
      '25%{background-position:37px 11px}' +
      '50%{background-position:61px 73px}' +
      '75%{background-position:17px 53px}' +
      '100%{background-position:0 0}}';
    const el = document.createElement('div');
    el.id = 'frontierGrain';
    el.style.cssText =
      'position:fixed;inset:0;z-index:1;pointer-events:none;' +
      'background-image:url(' + url + ');background-repeat:repeat;' +
      'mix-blend-mode:overlay;will-change:background-position;' +
      'animation:frontier-grain ' + dur + 's steps(1,end) infinite;opacity:0';
    document.head.appendChild(style);
    document.body.appendChild(el);
    this.grainStyle = style;
    this.grainEl = el;
    this.grainSeed = seed;
    this.syncGrain();
  }

  // Пресет мог смениться на лету (авто-тюнер) — слой не пересоздаём, а гасим.
  // Запись в style.opacity стоит один пересчёт композиции у браузера и делается
  // только когда значение действительно изменилось.
  syncGrain() {
    if (!this.grainEl) return;
    const want = (this.q && this.q.grainCss > 0) ? String(this.q.grainCss) : '0';
    if (this.grainEl.style.opacity !== want) this.grainEl.style.opacity = want;
  }

  // Полное снятие слоя — на случай выгрузки рендера (тесты, смена сцены).
  detachGrain() {
    if (this.grainEl && this.grainEl.parentNode) this.grainEl.parentNode.removeChild(this.grainEl);
    if (this.grainStyle && this.grainStyle.parentNode) this.grainStyle.parentNode.removeChild(this.grainStyle);
    this.grainEl = null; this.grainStyle = null; this.grainTried = false;
  }
}

// ---------------------------------------------------------------------------
// Мелкие помощники. Вынесены из класса, потому что не трогают состояние и
// проверяются тестом по отдельности.
// ---------------------------------------------------------------------------
function makeCanvas(w, h) {
  if (typeof document === 'undefined' || !document.createElement) return null;
  const cv = document.createElement('canvas');
  cv.width = Math.max(1, Math.round(w));
  cv.height = Math.max(1, Math.round(h));
  return cv;
}

export function bakeBrush(rgb) {
  const S = 64;
  const cv = makeCanvas(S, S);
  if (!cv) return null;
  const c = cv.getContext('2d');
  const g = c.createRadialGradient(S / 2, S / 2, 0, S / 2, S / 2, S / 2);
  g.addColorStop(0, `rgba(${rgb},0.55)`);
  g.addColorStop(0.30, `rgba(${rgb},0.26)`);
  g.addColorStop(0.65, `rgba(${rgb},0.08)`);
  g.addColorStop(1, `rgba(${rgb},0)`);
  c.fillStyle = g;
  c.fillRect(0, 0, S, S);
  return cv;
}

// Плитка плёночного зерна в виде data-URL. Строится один раз за сессию;
// toDataURL по 96×96 — это доли миллисекунды, но всё равно вызывается лениво,
// на первом кадре, где зерно вообще нужно (то есть только на ultra).
//
// Разброс ±34 от середины: при непрозрачности слоя 3 % и режиме overlay это
// даёт ту же зернистость, что прежний drawGrain с полным разбросом 0..255,
// но без «соли с перцем» — отдельные чёрные и белые пиксели на плитке
// читались как битые пиксели монитора.
export function grainDataUrl(seed) {
  const cv = makeCanvas(GRAIN_TILE, GRAIN_TILE);
  if (!cv || !cv.toDataURL) return null;
  const c = cv.getContext('2d');
  if (!c || !c.createImageData) return null;
  const img = c.createImageData(GRAIN_TILE, GRAIN_TILE);
  const d = img.data;
  for (let y = 0, i = 0; y < GRAIN_TILE; y++) {
    for (let x = 0; x < GRAIN_TILE; x++, i += 4) {
      const v = 128 + Math.round((hashP(seed, x, y, 7) - 0.5) * 68);
      d[i] = d[i + 1] = d[i + 2] = v;
      d[i + 3] = 255;
    }
  }
  c.putImageData(img, 0, 0);
  try { return cv.toDataURL('image/png'); } catch { return null; }
}

