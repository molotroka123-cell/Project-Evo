const clamp = (v, a, b) => (v < a ? a : v > b ? b : v);
const sstep = (a, b, x) => { const t = (x - a) / (b - a); return t <= 0 ? 0 : t >= 1 ? 1 : t * t * (3 - 2 * t); };

// Свой xorshift — см. шапку файла. Нужен ровно для того, чтобы развести
// шумовые решётки разных миров; в кадре не вызывается ни разу.
function makeRnd(seed) {
  let s = (seed | 0) || 0x9e3779b9;
  return () => {
    s ^= s << 13; s |= 0;
    s ^= s >>> 17;
    s ^= s << 5; s |= 0;
    return (s >>> 0) / 4294967296;
  };
}

// ---------------------------------------------------------------------------
// Заворачивающийся шум. fbm2 из palette.js честнее, но стоит четыре hash2 на
// октаву, а здесь до миллиона выборок за выпечку — это десятки миллисекунд на
// ровном месте. Решётка 128×128 считается один раз, выборка стоит четыре
// чтения и три интерполяции. Повтор в 128 единиц на двух разных частотах со
// сдвигом глазом не ловится.
// ---------------------------------------------------------------------------
const NT_SIZE = 128, NT_MASK = 127;

function makeNoiseTex(rnd) {
  const g = new Float32Array(NT_SIZE * NT_SIZE);
  for (let i = 0; i < g.length; i++) g[i] = rnd();
  return g;
}

function ntAt(g, x, y) {
  const xi = Math.floor(x), yi = Math.floor(y);
  const fx = x - xi, fy = y - yi;
  const sx = fx * fx * (3 - 2 * fx), sy = fy * fy * (3 - 2 * fy);
  const x0 = xi & NT_MASK, x1 = (xi + 1) & NT_MASK;
  const y0 = (yi & NT_MASK) * NT_SIZE, y1 = ((yi + 1) & NT_MASK) * NT_SIZE;
  const a = g[y0 + x0], b = g[y0 + x1], c = g[y1 + x0], d = g[y1 + x1];
  const t = a + (b - a) * sx, u = c + (d - c) * sx;
  return t + (u - t) * sy;
}

// ---------------------------------------------------------------------------
// РАНГ КЛЕТКИ — грубая лестница высоты по типу. Нужен для куполов массивов
// (см. buildDome): вершина тем выше, чем дальше она от края своего массива.
// ---------------------------------------------------------------------------
function rankOf(t) {
  if (t === TILE.DEEP) return 0;
  if (t === TILE.WATER) return 1;
  if (t === TILE.SAND) return 2;
  if (t === TILE.HILL) return 4;
  if (t === TILE.MOUNTAIN) return 5;
  return 3; // трава и лес — равнина
}

// ---------------------------------------------------------------------------
export class ReliefLayer {
  constructor(quality, opts = {}) {
    this.q = quality;
    this.opts = opts;
    this.enabled = opts.enabled !== false;

    this.seed = null;      // сид мира, по которому построено поле
    this.season = -1;      // сезон, под который испечены карты
    this.w = 0; this.h = 0;
    this.S = 0; this.SW = 0; this.SH = 0;

    this.H = null;         // Float32Array подрешётки: высота, уровень моря = 0
    this.Hlow = null;      // Float32Array по клеткам: сильно размытая высота
    this.tileH = null;     // Float32Array по клеткам: высота (для запросов извне)
    this.landK = null;     // Float32Array по клеткам: 1 суша, 0 вода (мягко)
    this.snowH = null;     // Float32Array по клеткам: высота снеговой линии
    this.nt = null;        // шумовая решётка мира
    this.Hrows = 0;        // сколько строк подрешётки уже посчитано
    this.rowTmp = null;    // промежуток горизонтального прохода сплайна
    this.bs = null;        // таблица весов вертикального прохода
    this.cliff0 = 0; this.cliff1 = 1;   // пороги обрыва этой карты (квантили)
    this.lapScale = 0.05;  // масштаб кривизны этой карты (квантиль)

    this.base = null; this.lite = null; this.iso = null;   // готовые карты
    this.job = null;       // состояние поэтапной выпечки
    this.buildMs = 0;      // сколько мс ушло на последнюю полную выпечку
    // Счётчики последней выпечки: сколько подпикселей получил каждый слой.
    // Не украшение — без них «пласты не видно» отличить от «пласты не
    // рисуются» можно только глазами по скриншоту.
    this.count = { cliff: 0, strata: 0, scree: 0, snow: 0, shadow: 0, light: 0 };
    this.drawn = 0;        // блитов в прошлом кадре — для отладочной панели
  }

  setQuality(q) {
    if (this.q === q) return;
    this.q = q;
    // Разрешение выпечки завязано на пресет — карты надо перепечь целиком.
    this.dropMaps();
    this.H = null; this.seed = null; this.Hrows = 0; this.rowTmp = null;
  }

  // Полный сброс (смена мира, ручная инвалидация).
  invalidate() {
    this.dropMaps();
    this.H = null; this.seed = null; this.season = -1;
    this.Hrows = 0; this.rowTmp = null;
  }

  dropMaps() {
    this.base = null; this.lite = null; this.iso = null;
    this.job = null; this.season = -1;
  }

  // Модуль молчит целиком: на пресетах, где рельефное освещение выключено
  // (кроме eco — там у него свой упрощённый путь), и в среде без DOM.
  get off() {
    if (!this.enabled) return true;
    if (typeof document === 'undefined') return true;
    return !this.q.relief && this.q.id !== 'eco';
  }

  // eco: только крупная форма и снег, одна карта, один блит.
  get simple() { return this.q.id === 'eco'; }

  // =========================================================================
  // ПОЛЕ ВЫСОТ
  // =========================================================================

  // Высота по клеткам. Два источника, и оба нужны.
  //
  // world.elev (worldgen2) — настоящее поле высот: материковые пятна, гребневой
  // шум, шельф. Но уровень моря в мире не записан: generateWorld2 режет сушу
  // КВАНТИЛЕМ и число никуда не сохраняет. Восстанавливаем его по границе
  // «самая высокая вода / самая низкая суша» — это ровно тот порог, по которому
  // тайлы и резались.
  //
  // Тип клетки — второй источник, и он обязателен даже при живом elev. Тайлы в
  // worldgen2 назначаются не по высоте, а по «горности» (гребень + высота),
  // поэтому клетка MOUNTAIN может сидеть на умеренной отметке. Если рисовать
  // рельеф строго по elev, гора окажется нарисована горой, но освещена как
  // равнина — картинка развалится на два несогласных слоя.
  buildTileHeight(world) {
    const w = world.w, h = world.h, N = w * h;
    const t = world.tiles;
    const Ht = new Float32Array(N);
    const elev = (world.elev && world.elev.length === N) ? world.elev : null;

    let sea = 0, span = 1;
    if (elev) {
      let wetMax = -Infinity, dryMin = Infinity, dryMax = -Infinity;
      for (let i = 0; i < N; i++) {
        const e = elev[i];
        if (t[i] === TILE.DEEP || t[i] === TILE.WATER) { if (e > wetMax) wetMax = e; }
        else { if (e < dryMin) dryMin = e; if (e > dryMax) dryMax = e; }
      }
      if (!isFinite(wetMax)) wetMax = isFinite(dryMin) ? dryMin : 0;   // мир без воды
      if (!isFinite(dryMin)) { dryMin = wetMax; dryMax = wetMax + 1; } // мир без суши
      sea = (wetMax + dryMin) * 0.5;
      span = Math.max(1e-4, dryMax - sea);
    }

    // Нормировка по типу: TILE_HEIGHT даёт −0,55…1,35, приводим к −0,41…1,0.
    for (let i = 0; i < N; i++) {
      const byTile = (TILE_HEIGHT[t[i]] ?? 0) / 1.35;
      Ht[i] = elev ? (elev[i] - sea) / span * 0.55 + byTile * 0.45 : byTile;
    }
    return { Ht, hasElev: !!elev };
  }

  // Купола массивов. Клетка тем выше, чем дальше она от ближайшей клетки более
  // низкого ранга. Без этого гряда из сорока клеток MOUNTAIN — идеальное плато
  // с отвесными краями: ровно то, как горы выглядят сейчас.
  //
  // Считается как пять волновых фронтов (по одному на ранг) — пять проходов
  // BFS по всей карте, O(N) каждый. На 96×96 это доли миллисекунды.
  buildDome(world, weight) {
    const w = world.w, h = world.h, N = w * h;
    const dome = new Float32Array(N);
    const dist = new Int32Array(N);
    const q = new Int32Array(N);
    // Ранг — в массив заранее. Вызов rankOf прямо во внутреннем цикле BFS
    // означал бы около миллиона вызовов функции на карте 192×192; это
    // измерено и стоило 10 мс из 43 всей сборки поля.
    const rank = new Uint8Array(N);
    for (let i = 0; i < N; i++) rank[i] = rankOf(world.tiles[i]);
    // Насколько «пухнет» каждый уровень и на каком расстоянии выходит на полку.
    const AMP = [0, 0.05, 0.05, 0.07, 0.16, 0.30];
    const REACH = [1, 3, 3, 5, 5, 7];

    for (let lvl = 1; lvl <= 5; lvl++) {
      dist.fill(-1);
      let qh = 0, qt = 0;
      for (let i = 0; i < N; i++) {
        if (rank[i] >= lvl) continue;
        dist[i] = 0; q[qt++] = i;                     // фронт: всё, что ниже уровня
      }
      if (!qt) continue;                              // ниже нет ничего — уровень не поднимаем
      while (qh < qt) {
        const i = q[qh++], x = i % w, y = (i / w) | 0, d = dist[i] + 1;
        for (let k = 0; k < 4; k++) {
          const nx = x + (k === 0 ? 1 : k === 1 ? -1 : 0);
          const ny = y + (k === 2 ? 1 : k === 3 ? -1 : 0);
          if (nx < 0 || ny < 0 || nx >= w || ny >= h) continue;
          const ni = ny * w + nx;
          if (dist[ni] >= 0 || rank[ni] < lvl) continue;
          dist[ni] = d; q[qt++] = ni;
        }
      }
      const amp = AMP[lvl] * weight, reach = REACH[lvl];
      for (let i = 0; i < N; i++) {
        if (dist[i] <= 0) continue;
        // Корень, а не линейка: подъём быстрый у края и пологий в середине —
        // так массив получает купол, а не пирамиду.
        dome[i] += amp * Math.sqrt(Math.min(dist[i], reach) / reach);
      }
    }
    return dome;
  }

  // Размытие 3×3 биномом. n проходов, вода не участвует в усреднении суши:
  // иначе весь берег уезжает под уровень моря и материк «тает» по кромке.
  //
  // Без маски ядро [1,2,1]⊗[1,2,1] РАЗДЕЛЯЕТСЯ на два одномерных прохода: три
  // отсчёта вместо девяти и никаких проверок границ во внутреннем цикле.
  // Это не микрооптимизация: крупная форма требует шести проходов, и на них
  // уходило 16 мс из 43 всей сборки поля. Маску разделить нельзя — там веса
  // зависят от соседей, — поэтому у неё остаётся честный путь 3×3.
  static blur(src, w, h, n, mask) {
    if (!mask) return ReliefLayer.blurFast(src, w, h, n);
    let a = src, b = new Float32Array(a.length);
    for (let p = 0; p < n; p++) {
      for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
          let s = 0, k = 0;
          for (let dy = -1; dy <= 1; dy++) {
            const yy = y + dy; if (yy < 0 || yy >= h) continue;
            for (let dx = -1; dx <= 1; dx++) {
              const xx = x + dx; if (xx < 0 || xx >= w) continue;
              const wgt = (dx === 0 ? 2 : 1) * (dy === 0 ? 2 : 1);
              const j = yy * w + xx;
              const m = mask ? mask[j] : 1;
              s += a[j] * wgt * m; k += wgt * m;
            }
          }
          b[y * w + x] = k > 0 ? s / k : a[y * w + x];
        }
      }
      const tmp = a; a = b; b = tmp;
    }
    return a;
  }

  // Разделимое размытие. Меняет ПЕРЕДАННЫЙ массив на месте и возвращает его.
  static blurFast(a, w, h, n) {
    const tmp = new Float32Array(a.length);
    for (let p = 0; p < n; p++) {
      for (let y = 0; y < h; y++) {
        const r = y * w;
        for (let x = 0; x < w; x++) {
          tmp[r + x] = (a[r + (x > 0 ? x - 1 : 0)] + 2 * a[r + x] + a[r + (x < w - 1 ? x + 1 : w - 1)]) * 0.25;
        }
      }
      for (let y = 0; y < h; y++) {
        const r = y * w, ru = (y > 0 ? y - 1 : 0) * w, rd = (y < h - 1 ? y + 1 : h - 1) * w;
        for (let x = 0; x < w; x++) a[r + x] = (tmp[ru + x] + 2 * tmp[r + x] + tmp[rd + x]) * 0.25;
      }
    }
    return a;
  }

  // Широкое размытие бегущей суммой: цена НЕ зависит от радиуса.
  //
  // Нужно оно ровно для крупной формы. Биномиальное 3×3 за шесть проходов даёт
  // σ около 1,7 клетки — на такой ширине разность «высота минус размытая
  // высота» составляет сотые доли и на экране не видна вообще. Замерено: слой
  // крупной формы не работал совсем, массив гор оставался мягким пятном. Здесь
  // радиус — около десятой доли карты, и разность наконец означает то, что
  // должна: «этот кусок выше своей округи».
  // Меняет переданный массив на месте и возвращает его.
  static boxBlur(a, w, h, r, passes) {
    const tmp = new Float32Array(a.length);
    const inv = 1 / (2 * r + 1);
    for (let p = 0; p < passes; p++) {
      for (let y = 0; y < h; y++) {
        const row = y * w;
        let sum = a[row] * (r + 1);
        for (let x = 1; x <= r; x++) sum += a[row + (x < w ? x : w - 1)];
        for (let x = 0; x < w; x++) {
          tmp[row + x] = sum * inv;
          const add = x + r + 1, sub = x - r;
          sum += a[row + (add < w ? add : w - 1)] - a[row + (sub > 0 ? sub : 0)];
        }
      }
      for (let x = 0; x < w; x++) {
        let sum = tmp[x] * (r + 1);
        for (let y = 1; y <= r; y++) sum += tmp[(y < h ? y : h - 1) * w + x];
        for (let y = 0; y < h; y++) {
          a[y * w + x] = sum * inv;
          const add = y + r + 1, sub = y - r;
          sum += tmp[(add < h ? add : h - 1) * w + x] - tmp[(sub > 0 ? sub : 0) * w + x];
        }
      }
    }
    return a;
  }

  // Кубический B-сплайн: веса одного отсчёта.
  //
  // ПОЧЕМУ ИМЕННО ОН, А НЕ БИЛИНЕЙНАЯ И НЕ CATMULL-ROM. Требование — никаких
  // ступенек по клеткам. Ступенька в ЦВЕТЕ убирается любой интерполяцией, но
  // свет считается по ПРОИЗВОДНОЙ высоты, а уступы — по второй производной.
  // У билинейной интерполяции производная рвётся на каждой границе клетки:
  // получается сетка светлых и тёмных полос. У Catmull-Rom рвётся вторая
  // производная — сетка проступает на кромках уступов. B-сплайн непрерывен
  // до второй производной включительно, поэтому решётка не видна нигде.
  // Плата — лёгкое сглаживание (сплайн приближающий, а не интерполирующий),
  // и это ровно то, что нужно переходу равнина→холм→гора.
  static bsplineTable(n, S) {
    const idx = new Int32Array(n), wt = new Float32Array(n * 4);
    for (let i = 0; i < n; i++) {
      const u = (i + 0.5) / S - 0.5;
      const iu = Math.floor(u), t = u - iu;
      const t2 = t * t, t3 = t2 * t;
      idx[i] = iu;
      wt[i * 4] = (1 - 3 * t + 3 * t2 - t3) / 6;
      wt[i * 4 + 1] = (4 - 6 * t2 + 3 * t3) / 6;
      wt[i * 4 + 2] = (1 + 3 * t + 3 * t2 - 3 * t3) / 6;
      wt[i * 4 + 3] = t3 / 6;
    }
    return { idx, wt };
  }

  // Полная сборка непрерывного поля высот. Не зависит от сезона — считается
  // один раз на мир.
  buildField(sim) {
    const world = sim.world;
    const w = world.w, h = world.h, N = w * h;
    const t = world.tiles;

    const S = this.pickSubres(w, h);
    const SW = w * S, SH = h * S;

    const rnd = makeRnd((world.seed ^ 0x5eed10ff) >>> 0);
    this.nt = makeNoiseTex(rnd);
    // Сдвиги решёток: два мира с одним рельефом не должны получить одинаковую
    // фактуру породы. Сдвиги берутся из своего rng, а не из rng ядра.
    this.ntOff = [rnd() * 512, rnd() * 512, rnd() * 512, rnd() * 512];

    const { Ht, hasElev } = this.buildTileHeight(world);
    // При живом elev купола нужны слабее: настоящая карта высот уже даёт форму,
    // и полный купол поверх неё превратил бы каждый массив в пудинг.
    // Купола слабее там, где есть настоящая карта высот, но не втрое: у
    // worldgen2 тип клетки назначается по «горности» (гребневой шум + высота),
    // и массив MOUNTAIN вполне может сидеть на умеренной отметке. Без купола
    // он рисуется горой, а освещается равниной — картинка разъезжается на два
    // несогласных слоя, что и было видно на первом прогоне: серый массив
    // оставался плоским пятном.
    const dome = this.buildDome(world, hasElev ? 0.7 : 1.0);

    const landK = new Float32Array(N);
    for (let i = 0; i < N; i++) {
      const wet = t[i] === TILE.DEEP || t[i] === TILE.WATER;
      landK[i] = wet ? 0 : 1;
      if (!wet) Ht[i] += dome[i];
    }

    // Суша сглаживается сама с собой (mask = landK), вода остаётся плоской:
    // её объём — дело water.js, а не наше.
    //
    // РОВНО ОДИН ПРОХОД, И ЭТО ИЗМЕРЕНО. Два прохода 3×3 размазывают перепад
    // «равнина → гора» на пять клеток: максимальный уклон на старой карте
    // падал до 0,25, обрывов не оставалось НИ ОДНОГО, и модуль превращался в
    // мягкую подсветку. Непрерывность перехода обеспечивает не размытие, а
    // кубический B-сплайн при разгоне на подрешётку (см. ниже) — он сам по
    // себе приближающий и снимает ступеньку по клеткам, ничего не теряя.
    const smooth = ReliefLayer.blur(Ht, w, h, 1, landK);
    // Нормировка: уровень моря 0, самая высокая суша 1. Свет и снеговая линия
    // считаются в этих единицах, поэтому они одинаково работают и на карте с
    // Эверестом, и на карте из одних дюн.
    let top = 1e-3;
    for (let i = 0; i < N; i++) if (landK[i] > 0 && smooth[i] > top) top = smooth[i];
    for (let i = 0; i < N; i++) smooth[i] /= top;

    // Крупная форма: та же высота, размытая ДО НЕУЗНАВАЕМОСТИ — радиус около
    // десятой доли карты. Разность даёт «этот кусок выше своей округи», то
    // есть то, что читается как массив, гряда и долина. Именно этого слоя нет
    // у terrain.js: там свет чисто локальный, и потому массив гор из сорока
    // клеток выглядит плоским, как бы ни были подсвечены отдельные клетки.
    const R = clamp(Math.round(Math.min(w, h) / 11), 3, 18);
    const low = ReliefLayer.boxBlur(Float32Array.from(smooth), w, h, R, 2);

    // Мягкая береговая маска: без неё рельеф обрывался бы по границе клетки
    // ровно там, где water.js рисует изогнутую кромку.
    const landSoft = ReliefLayer.blur(Float32Array.from(landK), w, h, 1, null);

    // Крутизна по клеткам — ей модулируется амплитуда мелкого шума: на
    // равнине рябь не нужна, на склоне она читается как фактура грунта.
    const slopeT = new Float32Array(N);
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const i = y * w + x;
        const l = smooth[y * w + Math.max(0, x - 1)], r = smooth[y * w + Math.min(w - 1, x + 1)];
        const u = smooth[Math.max(0, y - 1) * w + x], d = smooth[Math.min(h - 1, y + 1) * w + x];
        slopeT[i] = Math.hypot((r - l) * 0.5, (d - u) * 0.5);
      }
    }

    // ---- где начинается обрыв: квантиль, а не константа ----
    // Абсолютный порог — это лотерея по генератору. На карте worldgen2 уклон
    // доходит до 0,36, на старой generateWorld — до 0,25, а порог в 0,26 на
    // первой давал обрывы, на второй не давал ни одного: голая порода, пласты
    // и осыпь просто не появлялись на той карте, на которой игра и живёт.
    // Тем же приёмом (квантиль вместо порога) worldgen2 режет уровень моря и
    // долю гор — и ровно по той же причине.
    // Обычный массив с компаратором стоил здесь 22 мс из 43 всей сборки поля.
    // Типизированный массив сортируется родным численным сравнением.
    let nLand = 0;
    for (let i = 0; i < N; i++) if (landK[i] > 0) nLand++;
    const lands = new Float32Array(nLand);
    for (let i = 0, k = 0; i < N; i++) if (landK[i] > 0) lands[k++] = slopeT[i];
    lands.sort();
    const qAt = (q) => nLand ? lands[clamp(Math.floor(q * (nLand - 1)), 0, nLand - 1)] : 0;
    // Никаких поправочных коэффициентов: замер показал, что распределение
    // уклона по подпикселям и по клеткам совпадает в пределах ~15 %, а
    // выдуманный множитель 1,15 ровно на столько же и промахивался.
    const c0 = clamp(qAt(TUNE.cliffQ), TUNE.cliffMin, TUNE.cliffMax);
    this.cliff0 = c0;
    this.cliff1 = clamp(Math.max(qAt(TUNE.cliffQFull), c0 * 1.7), c0 * 1.4, TUNE.cliffFull);

    // ---- масштаб кривизны: тем же приёмом ----
    // Уступ и осыпь живут на второй производной высоты, а её порядок зависит
    // от карты ещё сильнее, чем уклон: 0,11 на старом генераторе против 0,06 на
    // worldgen2. Дальше в paintRow используется отношение к этому масштабу.
    const lapsArr = new Float32Array(nLand);
    for (let y = 0, k = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const i = y * w + x;
        if (landK[i] <= 0) continue;
        const l = smooth[y * w + Math.max(0, x - 1)], r = smooth[y * w + Math.min(w - 1, x + 1)];
        const u = smooth[Math.max(0, y - 1) * w + x], d = smooth[Math.min(h - 1, y + 1) * w + x];
        lapsArr[k++] = Math.abs(l + r + u + d - 4 * smooth[i]);
      }
    }
    lapsArr.sort();
    this.lapScale = clamp(
      nLand ? lapsArr[clamp(Math.floor(TUNE.lapQ * (nLand - 1)), 0, nLand - 1)] : TUNE.lapMin,
      TUNE.lapMin, TUNE.lapMax);

    // ---- разгон на подрешётку: горизонтальный проход ----
    // Вертикальный проход и мелкий рельеф считаются НЕ ЗДЕСЬ, а полосами по
    // мере покраски (см. ensureRows). Причина простая: полная сборка поля на
    // карте 192×192 стоит 60–80 мс, и если сделать её одним куском, первый
    // кадр новой партии проседает до 12 FPS. Горизонтальный проход дёшев
    // (SW × h отсчётов вместо SW × SH), его можно оставить синхронным.
    this.bs = ReliefLayer.bsplineTable(SH, S);
    const tx = ReliefLayer.bsplineTable(SW, S);
    // Таблица БИЛИНЕЙНОЙ выборки поклеточных полей — см. sampleAt.
    this.txA = new Int32Array(SW); this.txB = new Int32Array(SW); this.txF = new Float32Array(SW);
    for (let sx = 0; sx < SW; sx++) {
      const u = (sx + 0.5) / S - 0.5, i0 = Math.floor(u);
      this.txA[sx] = clamp(i0, 0, w - 1);
      this.txB[sx] = clamp(i0 + 1, 0, w - 1);
      this.txF[sx] = u - i0;
    }
    const rowTmp = new Float32Array(SW * h);
    for (let y = 0; y < h; y++) {
      const row = y * w, out = y * SW;
      for (let sx = 0; sx < SW; sx++) {
        const i0 = tx.idx[sx], o = sx * 4;
        const a = row + clamp(i0 - 1, 0, w - 1), b = row + clamp(i0, 0, w - 1);
        const c = row + clamp(i0 + 1, 0, w - 1), d = row + clamp(i0 + 2, 0, w - 1);
        rowTmp[out + sx] = smooth[a] * tx.wt[o] + smooth[b] * tx.wt[o + 1]
          + smooth[c] * tx.wt[o + 2] + smooth[d] * tx.wt[o + 3];
      }
    }
    this.rowTmp = rowTmp;
    this.Hrows = 0;                       // сколько строк подрешётки уже готово
    const H = new Float32Array(SW * SH);

    this.w = w; this.h = h; this.S = S; this.SW = SW; this.SH = SH;
    this.H = H; this.Hlow = low; this.tileH = smooth; this.landK = landSoft;
    this.slopeT = slopeT;
    this.seed = world.seed;
  }

  // Достроить строки поля высот до upTo. Вертикальный B-сплайн плюс мелкий
  // рельеф — то, что раньше считалось одним куском на 60–80 мс.
  //
  // МЕЛКИЙ РЕЛЬЕФ И ЕГО АМПЛИТУДА. Без него склон остаётся математически
  // гладким и читается как надутый пузырь; настоящий склон изрыт промоинами.
  // Но амплитуда тут крошечная, и это не осторожность, а арифметика: свет
  // считается по производной высоты, а производная бьёт по высокой частоте.
  // Рябь амплитудой 0,05 с периодом в четверть клетки даёт наклон 1,2 на
  // клетку — вчетверо круче настоящего горного склона. Такой «рельеф» — не
  // фактура, а белый шум поверх карты. Здесь амплитуда подобрана так, чтобы
  // вклад шума в наклон был около 0,13 на крутизне и около нуля на равнине.
  ensureRows(upTo) {
    const H = this.H;
    if (!H || this.Hrows >= upTo) return;
    const SW = this.SW, S = this.S, w = this.w, h = this.h;
    const ty = this.bs, rowTmp = this.rowTmp;
    const slopeT = this.slopeT, landSoft = this.landK;
    const g = this.nt, oA = this.ntOff[0], oB = this.ntOff[1];
    const invS = 1 / S;
    const end = Math.min(this.SH, upTo);
    for (let sy = this.Hrows; sy < end; sy++) {
      const j0 = ty.idx[sy], o = sy * 4;
      const ra = clamp(j0 - 1, 0, h - 1) * SW, rb = clamp(j0, 0, h - 1) * SW;
      const rc = clamp(j0 + 1, 0, h - 1) * SW, rd = clamp(j0 + 2, 0, h - 1) * SW;
      const out = sy * SW;
      const wy = sy * invS;
      // Амплитуда шума берётся по клеткам, но БИЛИНЕЙНО. Ступенчатая
      // амплитуда, помноженная на гладкий шум, даёт разрыв ровно по границам
      // клеток — то есть ту самую сетку, ради избавления от которой всё поле и
      // считается непрерывным. На увеличенном скриншоте она читалась как
      // стёганое одеяло по всему склону.
      const uy = (sy + 0.5) * invS - 0.5, jy = Math.floor(uy), fy = uy - jy;
      const jA = clamp(jy, 0, h - 1) * w, jB = clamp(jy + 1, 0, h - 1) * w;
      const txA = this.txA, txB = this.txB, txF = this.txF;
      for (let sx = 0; sx < SW; sx++) {
        let v = rowTmp[ra + sx] * ty.wt[o] + rowTmp[rb + sx] * ty.wt[o + 1]
          + rowTmp[rc + sx] * ty.wt[o + 2] + rowTmp[rd + sx] * ty.wt[o + 3];
        const iA = txA[sx], iB = txB[sx], fx = txF[sx];
        const s0 = slopeT[jA + iA] + (slopeT[jA + iB] - slopeT[jA + iA]) * fx;
        const s1 = slopeT[jB + iA] + (slopeT[jB + iB] - slopeT[jB + iA]) * fx;
        const l0 = landSoft[jA + iA] + (landSoft[jA + iB] - landSoft[jA + iA]) * fx;
        const l1 = landSoft[jB + iA] + (landSoft[jB + iB] - landSoft[jB + iA]) * fx;
        const amp = (0.002 + Math.min(0.014, (s0 + (s1 - s0) * fy) * 0.07)) * (l0 + (l1 - l0) * fy);
        if (amp >= 0.0004) {
          const wx = sx * invS;
          const n1 = ntAt(g, wx * 1.15 + oA, wy * 1.15 + oA) - 0.5;
          const n2 = ntAt(g, wx * 3.7 + oB, wy * 3.7 + oB) - 0.5;
          v += (n1 * 0.68 + n2 * 0.32) * amp;
        }
        H[out + sx] = v;
      }
    }
    this.Hrows = end;
    // Поле не зависит от сезона: как только оно достроено, промежуточный
    // буфер горизонтального прохода больше не нужен.
    if (this.Hrows >= this.SH) { this.rowTmp = null; this.bs = null; }
  }

  pickSubres(w, h) {
    const want = RELIEF_SUBRES[this.q.id] || 4;
    const side = Math.max(w, h);
    return Math.max(2, Math.min(want, Math.floor(RELIEF_MAX_SIDE / Math.max(1, side))));
  }

  // =========================================================================
  // СНЕГОВАЯ ЛИНИЯ
  //
  // По ВЫСОТЕ, а не по типу клетки. Ниже линии снега нет вовсе, выше он ложится
  // сплошняком, между — рваная кромка. Сама линия гуляет: она ниже у полюсов,
  // выше на экваторе, ниже зимой, ниже на северных склонах и выше на крутизне,
  // с которой снег просто сползает.
  // =========================================================================
  buildSnowLine(sim, season) {
    const world = sim.world, w = world.w, h = world.h, N = w * h;
    // Базовая отметка по сезону. Заметно ниже зимой — но НЕ драматически:
    // зимнюю белизну равнин рисует сезонная палитра TERRAIN[3], а этот слой
    // отвечает за снег ПО ВЫСОТЕ, то есть за то, что лежит круглый год.
    const BY_SEASON = [0.78, 0.92, 0.74, 0.52];
    const base = BY_SEASON[season] ?? 0.78;
    const temp = (world.temp && world.temp.length === N) ? world.temp : null;
    const Ht = this.tileH;
    const line = new Float32Array(N);
    const g = this.nt, oC = this.ntOff[2];
    for (let y = 0; y < h; y++) {
      // Широта: экватор — середина карты, полюса — верх и низ. Та же модель,
      // что в worldgen2.temperature, чтобы снег и биомы не спорили.
      const lat = Math.abs((y + 0.5) / h * 2 - 1);
      for (let x = 0; x < w; x++) {
        const i = y * w + x;
        // Тепло клетки: если worldgen2 подключён — из его слоя, иначе по широте.
        //
        // ВАЖНАЯ ПОПРАВКА. worldgen2.temperature уже вычитает высоту
        // (`- rel * 0.30`): по его модели гора холодная сама по себе. Если
        // взять temp как есть и ЕЩЁ раз сравнить с высотой, высота учтётся
        // дважды, и снеговая линия провалится ровно там, где горы, — весь
        // массив уходит под сплошной белый блин даже в разгар лета. Ровно это
        // и было видно на первом же прогоне. Возвращаем высотную поправку
        // обратно и получаем температуру «на уровне моря», с которой высоте
        // уже можно честно спорить.
        const warm = temp
          ? clamp(temp[i] + 0.30 * Math.max(0, Ht[i]), 0, 1)
          : clamp(1 - Math.pow(lat, 1.35), 0, 1);
        // Рваная кромка: без неё снеговая линия — идеальная изогипса.
        const n = ntAt(g, x * 0.42 + oC, y * 0.42 + oC) - 0.5;
        // Коэффициенты подобраны под нормировку «высшая точка суши = 1,0»:
        // летом на экваторе линия ложится около 0,88 (снег только на самой
        // макушке), у полюса около 0,45; зимой — 0,50 и 0,26. При прежних
        // числах экваториальная линия уходила за 1,0, и снега не оставалось
        // НИГДЕ И НИКОГДА — это ловится счётчиком stats().pct.snow.
        line[i] = clamp(base * (0.49 + warm * 0.47) + n * 0.07, 0.05, 2.0);
      }
    }
    this.snowH = line;
  }

  // =========================================================================
  // ВЫПЕЧКА
  // =========================================================================

  // Возвращает true, если в ЭТОМ кадре уже сделана тяжёлая работа. Сборка поля
  // высот и заведение выпечки (три канваса и три ImageData размером с карту)
  // — вещи разовые, но не бесплатные, и складывать их в один кадр с покраской
  // первой полосы незачем: так худший кадр загрузки складывался из трёх
  // расходов сразу. Разнесены по кадрам — и худший из них вдвое дешевле.
  ensure(sim) {
    const world = sim.world;
    if (!world || !world.tiles) return true;
    if (this.seed !== world.seed || !this.H) {
      this.dropMaps();
      this.buildField(sim);
      return true;
    }
    const season = sim.seasonIdx | 0;
    const want = this.job ? this.job.season : this.season;
    if (want !== season) { this.startJob(sim, season); return true; }
    return false;
  }

  startJob(sim, season) {
    const SW = this.SW, SH = this.SH;
    this.buildSnowLine(sim, season);
    const mk = () => {
      const cv = document.createElement('canvas');
      cv.width = SW; cv.height = SH;
      return { cv, c: cv.getContext('2d') };
    };
    const b = mk();
    const l = this.simple ? null : mk();
    const i = (this.simple || this.q.detail < 1) ? null : mk();
    this.count = { cliff: 0, strata: 0, scree: 0, snow: 0, shadow: 0, light: 0 };
    this.job = {
      season, y: 0, t0: now(),
      base: b, lite: l, iso: i,
      imgBase: b.c.createImageData(SW, SH),
      imgLite: l ? l.c.createImageData(SW, SH) : null,
      imgIso: i ? i.c.createImageData(SW, SH) : null,
      first: !this.base,
    };
  }

  // Один шаг выпечки. Возвращает true, когда карта готова.
  step(budgetMs) {
    const J = this.job;
    if (!J) return false;
    const t0 = now();
    const SH = this.SH;
    // Полосами по 4 строки: проверять часы на каждом пикселе дороже самой работы.
    while (J.y < SH) {
      const y1 = Math.min(SH, J.y + 4);
      // Покраска смотрит на полклетки вверх и вниз — строки под ней должны
      // быть уже посчитаны.
      this.ensureRows(y1 + Math.max(1, Math.round(this.S * 0.5)));
      for (let sy = J.y; sy < y1; sy++) this.paintRow(J, sy);
      J.y = y1;
      if (now() - t0 >= budgetMs) return false;
    }
    J.base.c.putImageData(J.imgBase, 0, 0);
    if (J.lite) J.lite.c.putImageData(J.imgLite, 0, 0);
    if (J.iso) J.iso.c.putImageData(J.imgIso, 0, 0);
    // Замена происходит АТОМАРНО, когда новая карта готова целиком: на экране
    // всё это время жила предыдущая, поэтому смена сезона не показывает
    // полурельеф и не моргает.
    this.base = J.base.cv;
    this.lite = J.lite ? J.lite.cv : null;
    this.iso = J.iso ? J.iso.cv : null;
    this.season = J.season;
    this.buildMs = now() - J.t0;
    this.job = null;
    return true;
  }

  // ---- одна строка подрешётки ----
  //
  // ДВА ШАБЛОНА, А НЕ ОДИН. Наклон для света берётся с шага в один подпиксель:
  // так в свет попадает мелкая фактура склона. А вот КРУТИЗНА (обрыв это или
  // нет) и КРИВИЗНА (бровка или подошва) считаются с шага в полклетки. Причина
  // арифметическая: производная усиливает высокие частоты, и на шаге в один
  // подпиксель рябь фактуры даёт кривизну в десятки раз больше, чем настоящий
  // перегиб рельефа. На узком шаблоне уступы утонули бы в сыпи случайных
  // бликов по всему склону.
  paintRow(J, sy) {
    const SW = this.SW, SH = this.SH, S = this.S, w = this.w, h = this.h;
    const H = this.H, low = this.Hlow, landK = this.landK, snowH = this.snowH;
    const pB = J.imgBase.data, pL = J.imgLite ? J.imgLite.data : null;
    const pI = J.imgIso ? J.imgIso.data : null;
    const simple = this.simple, detail = this.q.detail | 0;
    const g = this.nt, oD = this.ntOff[3];
    const CNT = this.count;

    const T = TUNE;
    // Пороги обрыва посчитаны по этой конкретной карте — см. buildField.
    const C0 = this.cliff0, C1 = this.cliff1;
    const invLap = 1 / (this.lapScale || 0.05);
    const ln = Math.hypot(T.sun[0], T.sun[1], T.sun[2]) || 1;
    const LX = T.sun[0] / ln, LY = T.sun[1] / ln, LZ = T.sun[2] / ln;
    const nz = 1 / T.exagg;
    const invS = 1 / S;

    // Широкий шаблон: полклетки, но не меньше одного подпикселя.
    const D = Math.max(1, Math.round(S * 0.5));
    const dTile = D * invS;                  // шаг широкого шаблона в клетках
    const invD = 1 / dTile, invD2 = invD * invD;

    const row = sy * SW;
    const rowUp = (sy > 0 ? sy - 1 : sy) * SW;
    const rowDn = (sy < SH - 1 ? sy + 1 : sy) * SW;
    const rowUpD = Math.max(0, sy - D) * SW;
    const rowDnD = Math.min(SH - 1, sy + D) * SW;
    const wy = sy * invS;
    // Билинейная выборка поклеточных полей. По ближайшей клетке крупная форма,
    // берег и снеговая линия рвались бы на границах клеток, и весь склон
    // покрывался бы сеткой — при том, что само поле высот непрерывно.
    const uy = (sy + 0.5) * invS - 0.5, j0 = Math.floor(uy), fy = uy - j0;
    const jA = clamp(j0, 0, h - 1) * w, jB = clamp(j0 + 1, 0, h - 1) * w;
    const txA = this.txA, txB = this.txB, txF = this.txF;
    let iA = 0, iB = 0, fx = 0;
    const bil = (arr) => {
      const a = arr[jA + iA], b = arr[jA + iB], c = arr[jB + iA], d = arr[jB + iB];
      const t = a + (b - a) * fx, u = c + (d - c) * fx;
      return t + (u - t) * fy;
    };

    // Накопитель цвета — premultiplied, чтобы слои складывались обычным
    // source-over. Объявлен НА СТРОКУ, а не на пиксель: замыкание внутри цикла
    // по подпикселям — это до миллиона лишних объектов за одну выпечку.
    let cr = 0, cg = 0, cb = 0, ca = 0;
    const over = (r, gg, b, a) => {
      if (a <= 0) return;
      const k = 1 - a;
      cr = r * a + cr * k; cg = gg * a + cg * k; cb = b * a + cb * k;
      ca = a + ca * k;
    };

    for (let sx = 0; sx < SW; sx++) {
      const i = row + sx;
      iA = txA[sx]; iB = txB[sx]; fx = txF[sx];
      const land = bil(landK);
      if (land <= 0.02) continue;                    // вода — не наш слой
      const o = i * 4;

      const hC = H[i];
      const xL = sx > 0 ? sx - 1 : sx, xR = sx < SW - 1 ? sx + 1 : sx;
      const xLD = Math.max(0, sx - D), xRD = Math.min(SW - 1, sx + D);

      // мелкий наклон — для света
      const gx = (H[row + xR] - H[row + xL]) * 0.5 * S;    // высота на клетку
      const gy = (H[rowDn + sx] - H[rowUp + sx]) * 0.5 * S;

      // широкий наклон и кривизна — для формы
      const gxW = (H[row + xRD] - H[row + xLD]) * 0.5 * invD;
      const gyW = (H[rowDnD + sx] - H[rowUpD + sx]) * 0.5 * invD;
      const slopeW = Math.sqrt(gxW * gxW + gyW * gyW);
      // Лапласиан: > 0 — вогнутость (подошва, лощина), < 0 — выпуклость (бровка).
      // Кривизна сразу в единицах «сколько это по меркам этой карты».
      const lap = (H[row + xLD] + H[row + xRD] + H[rowUpD + sx] + H[rowDnD + sx] - 4 * hC) * invD2 * invLap;

      // ---- ламберт ----
      const len = Math.sqrt(gx * gx + gy * gy + nz * nz) || 1;
      const nX = -gx / len, nY = -gy / len, nZ = nz / len;
      // Вычитание LZ обнуляет плоскость: ровная земля не имеет права ни
      // потемнеть, ни посветлеть от того, что поверх лёг ещё один слой.
      let v = (nX * LX + nY * LY + nZ * LZ - LZ) * T.micro;

      // ---- крупная форма ----
      // Высота минус её же сильное размытие: «этот кусок выше своей округи».
      // Ровно этого нет у terrain.js — там свет чисто локальный, и оттого
      // массив гор выглядит плоским, как бы ни были подсвечены его клетки.
      const macro = hC - bil(low);
      v += macro * (macro > 0 ? T.macroUp : T.macroDown);

      // ---- экспозиция склона ----
      // nY > 0 — склон смотрит вниз по экрану, то есть на юг.
      const asp = nY;
      v += asp * T.aspect;

      const cliff = sstep(C0, C1, slopeW);
      if (cliff > 0.25) CNT.cliff++;

      // ---- уступ ----
      // Бровка обрыва ловит свет, подошва уходит в тень. Именно эта пара
      // превращает наклонную плоскость в СТУПЕНЬ, которую видно сверху.
      if (!simple) v -= clamp(lap * T.ledgeN, -0.9, 0.9) * (0.35 + 0.65 * cliff);

      // ---------------- слои цвета, снизу вверх ----------------
      cr = 0; cg = 0; cb = 0; ca = 0;

      let strataLip = 0;
      if (!simple && detail >= 1 && cliff > 0.03) {
        // ---- голая порода на крутизне ----
        // Что бы ни было нарисовано на клетке — трава, лес, песок, — на
        // настоящем обрыве держится только камень. Это и есть «обрывы там,
        // где перепад резкий», а не намёк градиентом по кромке клетки.
        let rockK = cliff * 0.58;

        // ---- каменные пласты ----
        // Пласты идут по ИЗОЛИНИЯМ высоты (осадочная порода лежит слоями), а
        // частота залегания гуляет по карте: два соседних массива не должны
        // выглядеть одной и той же текстурой.
        const wx = sx * invS;
        const bed = 15 + ntAt(g, wx * 0.16 + oD, wy * 0.16 + oD) * 26;
        const warp = (ntAt(g, wx * 1.9 + 61, wy * 1.9 + 23) - 0.5) * 1.7;
        const ph = hC * bed + warp;
        const b = ph - Math.floor(ph);
        const seam = b < 0.17 ? 1 - b / 0.17 : 0;                         // тёмный шов
        strataLip = (b >= 0.17 && b < 0.36) ? 1 - (b - 0.17) / 0.19 : 0;  // освещённая полка
        const k = cliff * (detail >= 2 ? 1 : 0.6);
        if (seam * k > 0.25) CNT.strata++;
        over(T.rockRGB[0] * 0.62, T.rockRGB[1] * 0.62, T.rockRGB[2] * 0.62, seam * 0.30 * k);
        rockK *= 1 - seam * 0.25;
        over(T.rockRGB[0], T.rockRGB[1], T.rockRGB[2], rockK * 0.55);
      }

      // ---- осыпь ----
      // Щебень лежит там, где крутой склон выполаживается: вогнутость (lap > 0)
      // при ещё заметном уклоне. Это подножие обрыва — единственное место, где
      // осыпь вообще удерживается.
      if (!simple && detail >= 1) {
        // Окно крутизны привязано к порогу обрыва: осыпь лежит НИЖЕ обрыва,
        // на выполаживании, а не на самой стенке — с неё всё ссыпается.
        const foot = clamp(lap * T.screeCurv, 0, 1) * sstep(0.10, 0.24, hC)
          * sstep(C0 * 0.38, C0 * 1.10, slopeW) * (1 - sstep(C0 * 1.55, C1 * 1.15, slopeW));
        if (foot > 0.02) {
          if (foot > 0.15) CNT.scree++;
          // Зерно КРУПНОЕ: ячейка примерно в треть клетки. Хеш по каждому
          // подпикселю давал не осыпь, а цветную пыль — на увеличенном
          // скриншоте это читалось как шум кодека, а не как щебень.
          const gc = Math.max(1, S / 3);
          const grain = hash2(((sx / gc) | 0) * 7 + 13, ((sy / gc) | 0) * 11 + 5);
          const m = grain < 0.42 ? 0.72 : 1.16;
          over(T.screeRGB[0] * m, T.screeRGB[1] * m, T.screeRGB[2] * m,
            foot * (0.12 + Math.abs(grain - 0.5) * 0.26));
        }
      }

      // ---- снег ----
      // Крутая скала снега не держит, северный склон держит его ниже южного.
      const line = bil(snowH);
      const snow = sstep(line, line + 0.17, hC - asp * T.aspectSnow - slopeW * 0.34);
      if (snow > 0.4) CNT.snow++;
      if (snow > 0.01) over(T.snowRGB[0], T.snowRGB[1], T.snowRGB[2], snow * 0.78 * land);

      // ---- тень ----
      if (v < 0) {
        CNT.shadow++;
        // Тёплая на южном склоне, холодная на северном — та самая экспозиция.
        const warm = asp > 0 ? asp : 0, cool = asp < 0 ? -asp : 0;
        over(
          T.shadowRGB[0] + T.shadowWarm[0] * warm + T.shadowCool[0] * cool,
          T.shadowRGB[1] + T.shadowWarm[1] * warm + T.shadowCool[1] * cool,
          T.shadowRGB[2] + T.shadowWarm[2] * warm + T.shadowCool[2] * cool,
          Math.min(T.maxShadow, -v) * land,
        );
      }

      // Uint8ClampedArray сама обрезает и округляет — свой clamp тут был бы
      // лишней работой на каждом из миллиона подпикселей.
      if (ca > 0.0016) {
        const inv = 1 / ca;
        pB[o] = cr * inv;
        pB[o + 1] = cg * inv;
        pB[o + 2] = cb * inv;
        pB[o + 3] = ca * 255;
      }

      // ---- солнечная сторона ----
      if (pL) {
        let a = v > 0 ? Math.min(T.maxLight, v) : 0;
        a += strataLip * 0.10;             // блик на полке пласта
        a *= (1 + snow * 0.55);            // снег отражает больше
        a = Math.min(0.34, a) * land;
        if (a > 0.004) {
          CNT.light++;
          // На снегу свет холоднее, на породе и траве — тёплый солнечный.
          pL[o] = T.lightRGB[0];
          pL[o + 1] = T.lightRGB[1] + (250 - T.lightRGB[1]) * snow;
          pL[o + 2] = T.lightRGB[2] + (255 - T.lightRGB[2]) * snow;
          pL[o + 3] = a * 255;
        }
      }

      // ---- изогипсы ----
      // Расстояние до ближайшей изолинии переводится из «высоты» в «клетки»
      // делением на модуль градиента — поэтому линия получается одинаковой
      // ширины и на пологом склоне, и на крутом, а на плоскости не рисуется
      // вовсе: там градиент ноль и ближайшая изолиния бесконечно далеко.
      if (pI && slopeW > 1e-4) {
        const f = hC / T.isoStep;
        const nrst = Math.round(f);
        const d = Math.abs(f - nrst) * T.isoStep / slopeW;   // в клетках
        const a0 = 1 - sstep(T.isoWidth * 0.45, T.isoWidth, d);
        if (a0 > 0.01) {
          // Каждая пятая — утолщённая: по ним считают высоту, как на карте.
          const a = a0 * ((nrst % T.isoIndex) === 0 ? 0.42 : 0.22) * land;
          pI[o] = T.isoRGB[0]; pI[o + 1] = T.isoRGB[1]; pI[o + 2] = T.isoRGB[2];
          pI[o + 3] = a * 255;
        }
      }
    }
  }

  // =========================================================================
  // КАДР
  // =========================================================================
  //
  // Всё, что здесь происходит: посчитать видимый прямоугольник карты и сделать
  // два-три drawImage. Никаких примитивов, никаких проходов по клеткам.
  draw(sim, ctx, ox, oy, z, cw, ch, L) {
    this.drawn = 0;
    if (this.off || !sim || !sim.world) return;
    const busy = this.ensure(sim);
    if (!busy && this.job) this.step(this.job.first ? RELIEF_BUDGET.first : RELIEF_BUDGET.rebake);
    if (!this.base) return;

    const S = this.S, w = this.w, h = this.h;
    // Видимая область в клетках, с запасом в клетку по краям.
    const x0 = clamp(Math.floor((-ox) / z) - 1, 0, w);
    const x1 = clamp(Math.ceil((cw - ox) / z) + 1, 0, w);
    const y0 = clamp(Math.floor((-oy) / z) - 1, 0, h);
    const y1 = clamp(Math.ceil((ch - oy) / z) + 1, 0, h);
    if (x1 <= x0 || y1 <= y0) return;

    const sx = x0 * S, sy = y0 * S, sw = (x1 - x0) * S, sh = (y1 - y0) * S;
    const dx = ox + x0 * z, dy = oy + y0 * z;
    const dw = (x1 - x0) * z, dh = (y1 - y0) * z;

    // Контраст рельефа живёт по солнцу: он максимален на рассвете и закате,
    // когда свет идёт вскользь, чуть слабее в полдень и почти исчезает ночью,
    // где форму показывает не солнце, а небо.
    let k = 1;
    if (L && typeof L.mul === 'number') {
      const sun = clamp((L.mul - 0.42) / 0.58, 0, 1);
      k = clamp(0.52 + sun * 0.50 + Math.sin(Math.PI * sun) * 0.30, 0.45, 1.16);
    }

    ctx.save();
    ctx.imageSmoothingEnabled = true;
    // Фильтр — билинейный, и это не экономия «на всякий случай», а замер.
    // Карта печётся в 6 пикселей на клетку, а на экране клетка занимает 20–40,
    // то есть слой ВСЕГДА растягивается. На растяжении гладкой карты освещения
    // бикубик от билинейного глазом не отличается: резких кромок в источнике
    // нет по построению. А стоит он на программном растеризаторе всё:
    //   'high' — 25 FPS,  'low' — 61 FPS  (общий вид карты, пресет «высоко»).
    // Именно из-за этой строки рельеф полгода стоял выключенным везде, кроме
    // «ультра», и считался «дорогим слоем». Дорогим был фильтр.
    ctx.imageSmoothingQuality = 'low';
    // База (порода, осыпь, снег, тень) гаснет ночью лишь частично: снег и
    // скала никуда не деваются от того, что село солнце.
    ctx.globalAlpha = clamp(0.72 + 0.28 * k, 0, 1);
    ctx.drawImage(this.base, sx, sy, sw, sh, dx, dy, dw, dh);
    this.drawn++;

    if (this.lite) {
      ctx.globalCompositeOperation = 'lighter';
      ctx.globalAlpha = clamp(k, 0, 1);
      ctx.drawImage(this.lite, sx, sy, sw, sh, dx, dy, dw, dh);
      ctx.globalCompositeOperation = 'source-over';
      this.drawn++;
    }

    // Изогипсы — подсказка формы там, где детали физически не видно: клетка
    // мельче 23 экранных пикселей. Вблизи они выключаются полностью, иначе
    // карта превращается в чертёж.
    if (this.iso && z < ISO_MAX_PX) {
      const a = sstep(ISO_MAX_PX, ISO_FULL_PX, z);
      if (a > 0.02) {
        ctx.globalAlpha = a * 0.85;
        ctx.drawImage(this.iso, sx, sy, sw, sh, dx, dy, dw, dh);
        this.drawn++;
      }
    }
    ctx.restore();
  }

  // =========================================================================
  // ЗАПРОСЫ (для других слоёв и отладки; в кадре не обязательны)
  // =========================================================================

  // Нормированная высота клетки: 0 — уровень моря, 1 — высшая точка суши.
  heightAt(x, y) {
    if (!this.tileH) return 0;
    const xi = Math.floor(x), yi = Math.floor(y);
    if (xi < 0 || yi < 0 || xi >= this.w || yi >= this.h) return 0;
    return this.tileH[yi * this.w + xi];
  }

  // Крутизна клетки: перепад нормированной высоты на клетку.
  slopeAt(x, y) {
    if (!this.slopeT) return 0;
    const xi = Math.floor(x), yi = Math.floor(y);
    if (xi < 0 || yi < 0 || xi >= this.w || yi >= this.h) return 0;
    return this.slopeT[yi * this.w + xi];
  }

  // Обрыв ли здесь — по той же шкале, что и картинка.
  isCliff(x, y) { return this.cliff0 > 0 && this.slopeAt(x, y) >= this.cliff0; }

  // Лежит ли снег: 0 — нет, 1 — сплошной. Считается по высоте и снеговой
  // линии, а не по типу клетки.
  snowAt(x, y) {
    if (!this.snowH || !this.tileH) return 0;
    const xi = Math.floor(x), yi = Math.floor(y);
    if (xi < 0 || yi < 0 || xi >= this.w || yi >= this.h) return 0;
    const i = yi * this.w + xi;
    return sstep(this.snowH[i], this.snowH[i] + 0.17, this.tileH[i] - this.slopeT[i] * 0.34);
  }

  // Русская строка для тултипа клетки.
  describe(x, y) {
    if (!this.tileH) return '';
    const hgt = this.heightAt(x, y), s = this.slopeAt(x, y), sn = this.snowAt(x, y);
    if (hgt <= 0) return 'под водой';
    const parts = [`высота ${Math.round(hgt * 100)}`];
    if (s >= this.cliff1) parts.push('отвесный обрыв');
    else if (s >= this.cliff0) parts.push('крутой склон');
    else if (s >= this.cliff0 * 0.45) parts.push('склон');
    if (sn > 0.55) parts.push('снега');
    else if (sn > 0.1) parts.push('пятна снега');
    return parts.join(', ');
  }

  stats() {
    return {
      sub: this.S, size: this.SW + '×' + this.SH,
      maps: (this.base ? 1 : 0) + (this.lite ? 1 : 0) + (this.iso ? 1 : 0),
      mb: +(((this.SW * this.SH * 4) * ((this.base ? 1 : 0) + (this.lite ? 1 : 0) + (this.iso ? 1 : 0))) / 1048576).toFixed(1),
      buildMs: +this.buildMs.toFixed(1),
      baking: !!this.job, progress: this.job ? +(this.job.y / this.SH).toFixed(2) : 1,
      drawn: this.drawn,
      cliff0: +this.cliff0.toFixed(3), cliff1: +this.cliff1.toFixed(3),
      // доля подпикселей карты, доставшаяся каждому слою (в процентах)
      pct: Object.fromEntries(Object.entries(this.count)
        .map(([k, v]) => [k, +(v / Math.max(1, this.SW * this.SH) * 100).toFixed(1)])),
    };
  }
}

function now() {
  return (typeof performance !== 'undefined' && performance.now) ? performance.now() : Date.now();
}

