// render/relief.js — РЕЛЬЕФ: объём местности, обрывы, пласты, осыпи,
// снеговая линия и изогипсы.
//
// ═══════════════════════════ ЗАЧЕМ ═══════════════════════════
// Сейчас высота на карте существует только как ТИП КЛЕТКИ. terrain.buildHeight
// берёт TILE_HEIGHT[tile], сглаживает 3×3 и считает ламберта — то есть высота
// холма ровно одна на всю гряду, а высота горы одна на весь массив. Следствия
// видны на любом скриншоте:
//   • гряда гор — плато с отвесным краем, а не хребет с вершиной и склонами;
//   • переход равнина→холм→гора идёт ступенькой по клетке: на стыке видна
//     ровная линия, потому что между 0,10 и 0,62 нет ничего;
//   • обрыв рисуется одним градиентом по нижней кромке клетки (terrain.edges) —
//     это подсказка, а не форма;
//   • снег лежит «на клетках типа гора», а не выше снеговой линии, поэтому
//     на экваторе он такой же, как за полярным кругом;
//   • сверху, на дальнем зуме, форма местности не читается вовсе.
// Гора отличается от равнины цветом и треугольничками. Должна — ФОРМОЙ И СВЕТОМ.
//
// ═══════════════════ ЧТО ДЕЛАЕТ ЭТОТ МОДУЛЬ ═══════════════════
// Строит НЕПРЕРЫВНОЕ поле высот (не поклеточное) и печёт по нему три карты
// размером с мир, которые в кадре только блитятся:
//   base — тень + голая порода на крутизне + осыпь + снег (source-over);
//   lite — солнечная сторона и блик на кромках уступов ('lighter');
//   iso  — изогипсы, включаются только на дальнем зуме (source-over).
// Всё, что стоит дорого, происходит при выпечке; кадр платит 2–3 drawImage.
//
// Источник высоты — слой world.elev из core/systems/worldgen2.js (настоящая
// карта высот с материками, хребтами и шельфом). Если игра ещё живёт на старом
// generateWorld и слоя нет, высота честно реконструируется из типов клеток —
// смотри buildTileHeight(): купола массивов через дистанционное преобразование
// плюс когерентный шум. Модуль полезен в обоих случаях, но с worldgen2 он
// показывает НАСТОЯЩУЮ географию, а не догадку о ней.
//
// ═══════════════════════ ГРАНИЦЫ ═══════════════════════
// Модуль читает симуляцию (world.tiles, world.elev, world.temp, world.biome,
// sim.seasonIdx) и НИЧЕГО в ней не меняет. Он не трогает ни один существующий
// файл: подключение описано внизу, в блоке «ПОДКЛЮЧЕНИЕ». Импорт файла не имеет
// побочных эффектов — до первого кадра не печётся ни одного канваса.
//
// СЛУЧАЙНОСТЬ. Math.random запрещён, rng ядра трогать нельзя: каждый его вызов
// сдвигает состояние симуляции, а рендер у разных игроков идёт с разной
// частотой — сейв бы поплыл. Здесь свой xorshift от sim.world.seed плюс
// детерминированные hash2/noise2 из palette.js. Ровно так же устроены
// weather.js, water.js и fx.js.
