// render/city_lights.js — огни города ночью: окна на фасадах и пятна света
// на земле вокруг освещённых построек.
//
// ЗАЧЕМ. До этого слоя ночь работала ровно одним способом: палитра множила
// землю на 0,42 и заливала кадр синим тоном. Город становился тёмным пятном
// той же формы, что и днём, — ни одного признака, что в нём кто-то живёт.
// Свечение окон в renderer уже было, но оно живёт только у ПРОЦЕДУРНЫХ
// спрайтов (карта spr.glow печётся вместе со спрайтом), а 39 построек из 58
// рисуются нарисованным артом, и у них ночью не горит ничего. Плюс свет
// нигде не падал на землю, а именно пятна на земле и читаются как «город».
//
// ЧТО ДЕЛАЕТ.
//   1. Окна. Поверх прямоугольника спрайта (НЕ поверх его содержимого —
//      содержимое у арта и у процедурки разное, а прямоугольник один и тот же)
//      блитится испечённый узор окон. Узор зависит от эпохи постройки:
//      каменный век — две-три оранжевые точки костра, индустриальная —
//      плотная сетка жёлтых окон, будущее — холодные голубые полосы.
//   2. Разнобой. Окна зажигаются НЕ разом. У каждой постройки свой порог
//      темноты, взятый детерминированным хешем от её координат и сида мира,
//      и внутри постройки окна загораются группами — узор испечён шестью
//      кадрами нарастающей заполненности, в кадре выбирается номер кадра.
//   3. Пятна на земле. Тёплый (или холодный, по эпохе) круг под каждой
//      освещённой постройкой. Все круги складываются в ОДИН offscreen-слой
//      половинного разрешения и накладываются на кадр одним блитом в режиме
//      'lighter'. Наивный путь — по кругу на здание прямо в кадр — это 160
//      полупрозрачных заливок по основному холсту вместо одной.
//
// ЦЕНА КАДРА (оценка; стенд из docs/visual-performance-budget.md —
// SwiftShader, растеризация на CPU, 1280×720, то есть худший случай):
//   днём (L.glow < 0,03) ........................ 0 мс, ранний выход в begin()
//   ночью, high, город 150 построек:
//     обход построек, два хеша на штуку ......... ~0,02 мс
//     очистка слоя пятен (640×360) .............. ~0,15 мс
//     ~150 блитов градиента в слой пятен ........ ~0,35 мс
//     один блит слоя пятен на кадр в 'lighter' .. ~0,50 мс
//     ~150 блитов узора окон (около 40×40 px) ... ~0,30 мс
//   итого ..................................... ~1,3 мс из 16,6
//   на eco слой пятен не создаётся вовсе (остаются только окна) — ~0,2 мс.
// На настоящем GPU-канвасе всё это заметно дешевле: здесь нет ни одного
// filter/blur в кадре и ни одного getImageData. Все размытия — только в
// выпечке, которая случается 20-30 раз за партию и стоит ~0,1 мс за штуку.
//
// СЛУЧАЙНОСТЬ. Ни Math.random, ни sim.rng. Рендер идёт с разной частотой у
// разных игроков, и вызов sim.rng сдвинул бы состояние симуляции — сейв бы
// поплыл. Здесь тот же смеситель, что в palette.hash2, но с сидом мира и
// солью (hashB), и отдельный xorshift для выпечки узора (makeRnd) — ровно
// как в water.js / relief.js / vegetation.js.
import { ERA_PALETTE, hex2rgb } from './palette.js';
import { BUILDING_ERA_IDX } from '../core/data.js';
import { lodForZoom, prune, canvasBytes } from './quality.js';

// Мировая единица «тайл→экран» при zoom = 1. Дублируется из renderer.js
// намеренно: она не зависит от пресета графики и не экспортируется оттуда,
// а тянуть renderer в этот файл — кольцевая зависимость.
const TILE_PX = 32;

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

// Тот же смеситель, что palette.hash2, но принимает сид мира и соль: одна и
// та же постройка в одном и том же мире всегда получает одно и то же число,
// а разные свойства (порог зажигания, вариант узора, фаза мерцания) не
// коррелируют между собой — иначе все «поздние» дома оказались бы ещё и
// одинакового вида.
function hashB(seed, x, y, salt) {
  let h = (x * 374761393 + y * 668265263 + seed * 1442695041 + salt * 2246822519) | 0;
  h = (h ^ (h >>> 13)) * 1274126177 | 0;
  return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
}

// xorshift для выпечки узора. Выпечка идёт вне кадра, но всё равно обязана
// быть детерминированной: иначе после смены пресета (кэши чистятся) город
// перекрасил бы окна на глазах у игрока.
function makeRnd(seed) {
  let s = (seed | 0) || 0x51ed270b;
  return () => {
    s ^= s << 13; s |= 0;
    s ^= s >>> 17;
    s ^= s << 5; s |= 0;
    return (s >>> 0) / 4294967296;
  };
}

// ---------------------------------------------------------------------------
// Классы узора по эпохе.
//
// Деление не по «красиво», а по тому, чем на самом деле светилось жильё:
//   fire  (каменный, бронзовый) — открытый огонь, окон нет вообще. Две-три
//         дрожащие точки у земли, крупные и мягкие.
//   lamp  (железо…ренессанс) — масло и свеча. Проёмы редкие, мелкие,
//         расставлены неровно: регулярная сетка появилась только с рамой.
//   grid  (индустриальная, современность) — электричество и одинаковые рамы.
//         Плотные ряды, тот самый «жёлтый в клетку».
//   strip (информационная, будущее) — сплошное остекление. Не точки, а
//         горизонтальные полосы во всю ширину фасада, холодные.
// ---------------------------------------------------------------------------
export const WINDOW_CLASS = ['fire', 'fire', 'lamp', 'lamp', 'lamp', 'lamp', 'grid', 'grid', 'strip', 'strip'];

export function windowClass(era) {
  return WINDOW_CLASS[Math.max(0, Math.min(9, era | 0))];
}

// Тёплые эпохи против холодных — решает цвет пятна на земле. Граница на 7:
// с «современности» ERA_PALETTE.glow уже голубой (#a8e2ff), и тёплое пятно
// под таким зданием выглядит как чужая лампа под окном.
export function warmEra(era) {
  return (era | 0) < 7;
}

// Сколько кадров нарастающей заполненности печём в атлас. Шесть — компромисс:
// при четырёх видно ступеньку «загорелась четверть дома», при двенадцати
// атлас вдвое шире, а разницу на 40 экранных пикселях уже никто не увидит.
const STEPS = 6;

// Сторона кадра узора в атласе. 48 px — это чуть больше, чем окно занимает на
// экране при обычном зуме (постройка в один тайл — 32-40 px), то есть узор
// всегда ужимается, а не растягивается: ужатие прощает всё, растяжение делает
// из окна размытую кляксу.
const FRAME = 48;

// Вариантов узора на эпоху. Три достаточно, чтобы соседние одинаковые хижины
// не выглядели копиями, и мало настолько, чтобы весь атлас всех эпох сразу
// весил 10*3*(48*7)*48*4 ≈ 1,9 МБ — вписывается в самый скромный spriteMB.
const VARIANTS = 3;

// Сколько атласов разрешено испечь за один кадр. Выпечка одного — это ~150
// мелких fillRect с shadowBlur, порядка 0,1 мс; при смене эпохи или пресета
// запрос может прийти сразу на десяток. Ограничение размазывает всплеск на
// несколько кадров; постройка, узор которой ещё не готов, просто один кадр
// стоит без окон — на 16 мс этого не видно.
const BAKES_PER_FRAME = 3;

// ---------------------------------------------------------------------------
// Кривая зажигания.
//
// L.glow из palette.lightAt — это «насколько сейчас ночь»: 0 в полдень, 1 в
// полночь, с плавными переходами на 0,26 и 0,78 суток. Прямо по ней зажигать
// нельзя: получится, что весь город щёлкает выключателем одновременно.
//
// Поэтому у постройки есть собственный порог thr ∈ [0,10; 0,52] от хеша, и
// доля горящих окон — это насколько ночь этот порог превысила, растянутое на
// SPAN. При glow = 1 (полночь) горят все: даже самый «поздний» дом с порогом
// 0,52 даёт (1 − 0,52)/0,45 > 1.
const THR_LO = 0.10, THR_HI = 0.52, SPAN = 0.45;

// Асимметрия вечера и утра. Вечером свет включают охотно и заранее (порог
// ниже), утром гасят при первых признаках света (порог выше). Без этого
// вечер и утро зеркальны, и ночь выглядит записанной задом наперёд.
// 0,07 — примерно четверть разброса порогов: заметно, но не переворачивает
// порядок, в котором дома зажигаются.
const DUSK_BIAS = -0.07, DAWN_BIAS = 0.07;

// dayTime ∈ [0,1): 0 — полночь, 0.5 — полдень. Вечер — вторая половина суток.
export function phaseBias(dayTime) {
  const t = ((dayTime % 1) + 1) % 1;
  return t > 0.5 ? DUSK_BIAS : DAWN_BIAS;
}

// Доля горящих окон конкретной постройки, [0..1].
export function litFill(seed, x, y, night, bias) {
  const thr = THR_LO + (THR_HI - THR_LO) * hashB(seed, x, y, 1) + (bias || 0);
  return clamp01((night - thr) / SPAN);
}

// Номер кадра узора в атласе: 0 — не горит ничего (блит пропускаем).
export function frameIndex(fill) {
  return Math.max(0, Math.min(STEPS, Math.ceil(clamp01(fill) * STEPS)));
}

