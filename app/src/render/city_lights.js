// Погода. Взвесь в воздухе рассеивает свет: в тумане фонарь виден дальше и
// как большее пятно, в дождь мокрый асфальт возвращает часть света вверх.
// Числа — не измерение, а согласование с WEATHER_TINT из palette.js: там же
// туман гасит картинку сильнее всех (mul 0,86 плюс плотный серый тон), и без
// компенсации город в тумане ночью пропадал бы совсем.
// Окна взвесь наоборот приглушает — светится не окно, а воздух перед ним.
export const WEATHER_LIGHT = {
  sun:   { pool: 1.00, radius: 1.00, win: 1.00 },
  cloud: { pool: 1.05, radius: 1.02, win: 1.00 },
  rain:  { pool: 1.18, radius: 1.08, win: 0.92 },
  storm: { pool: 1.22, radius: 1.10, win: 0.88 },
  snow:  { pool: 1.12, radius: 1.06, win: 0.96 },
  fog:   { pool: 1.30, radius: 1.28, win: 0.80 },
  heat:  { pool: 1.00, radius: 1.00, win: 1.00 },
};
const WEATHER_DEFAULT = WEATHER_LIGHT.sun;

// ---------------------------------------------------------------------------
// Фасадная зона внутри прямоугольника спрайта.
//
// Модуль НЕ знает, что нарисовано внутри: у арта постройка занимает середину
// кадра с прозрачными полями, у процедурного спрайта сверху запас под конёк и
// трубу (в sprites.js это множитель 1,12 к высоте архетипа). Единственное,
// на что можно опереться, — сам прямоугольник. Поэтому зона окон задана
// долями от него, и доли выбраны так, чтобы не вылезти за силуэт ни там, ни
// там: по ширине берём центральные 60 %, по высоте — полосу под крышей.
//
// Отдельная ветка для башен: у небоскрёба и шпиля высота втрое больше ширины,
// и полоса «под крышей» на 52 % высоты оставила бы две трети ствола тёмными.
const TOWER_ASPECT = 1.6;

export function facadeRect(dx, dy, dw, dh) {
  const tower = dh > dw * TOWER_ASPECT;
  const top = tower ? 0.18 : 0.30;
  const height = tower ? 0.64 : 0.52;
  return {
    x: dx + dw * 0.20,
    y: dy + dh * top,
    w: dw * 0.60,
    h: dh * height,
  };
}

// ---------------------------------------------------------------------------
// Раскладка окон внутри кадра атласа. Возвращает массив
// { x, y, w, h, r, rank, soft }, координаты — доли кадра [0..1].
// rank ∈ [0..1) — очередь зажигания: кадр k показывает окна с rank < k/STEPS.
// Вынесено наружу и чисто (без канваса), чтобы тест мог проверить раскладку,
// не имея DOM.
const CLASS_SALT = { fire: 1, lamp: 2, grid: 3, strip: 4 };

export function layoutWindows(cls, variant) {
  // Сид раскладки НЕ включает эпоху намеренно: внутри одного класса узор
  // должен быть общим, эпоха меняет только цвет. Иначе при переходе
  // индустриальная → современность (оба класса grid) весь город разом
  // переставил бы окна, хотя дома не перестраивались.
  const rnd = makeRnd(0x9e3779b1 ^ (variant * 2654435761) ^ ((CLASS_SALT[cls] || 0) * 40503));
  const out = [];
  const push = (x, y, w, h, soft) => out.push({ x, y, w, h, soft, rank: rnd() });

  if (cls === 'fire') {
    // Костёр и очаг — не окно: свет выходит через дверной проём и дымоход,
    // то есть внизу и по центру. Точки крупные и мягкие, их мало.
    const n = 2 + (variant % 2);
    for (let i = 0; i < n; i++) {
      const w = 0.16 + rnd() * 0.06;
      push(0.30 + (i - (n - 1) / 2) * 0.26 + (rnd() - 0.5) * 0.06, 0.58 + rnd() * 0.18, w, w * 0.9, true);
    }
    return out;
  }

  if (cls === 'lamp') {
    // Неровная сетка: 2-3 столбца, 2 ряда, каждый проём смещён на случайную
    // долю шага. Ровная сетка тут читается как индустриальная эпоха и ломает
    // всю затею с различием эпох.
    const cols = 2 + (variant % 2);
    const rows = 2;
    const w = 0.13, h = 0.17;
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        if (rnd() < 0.18) continue;      // часть проёмов заколочена/тёмная
        const cx = (c + 0.5) / cols, cy = 0.28 + r * 0.34;
        push(cx - w / 2 + (rnd() - 0.5) * 0.06, cy + (rnd() - 0.5) * 0.05, w, h, false);
      }
    }
    return out;
  }

  if (cls === 'grid') {
    // Ряды одинаковых рам. 4-5 столбцов и 3 ряда — на 48 px кадра это окно
    // шириной 5 px, ниже уже каша при ужатии до 40 px на экране.
    const cols = 4 + (variant % 2);
    const rows = 3;
    const w = 0.11, h = 0.13;
    for (let r = 0; r < rows; r++) {
      for (let c = 0; c < cols; c++) {
        if (rnd() < 0.12) continue;      // пустующая квартира
        push((c + 0.5) / cols - w / 2, 0.16 + r * 0.28, w, h, false);
      }
    }
    return out;
  }

  // strip: сплошное остекление. Полоса во всю ширину с одним разрывом —
  // разрыв нужен, чтобы полоса читалась как ряд окон, а не как неоновая
  // трубка по фасаду.
  const rows = 4;
  for (let r = 0; r < rows; r++) {
    const y = 0.14 + r * 0.20;
    const gap = 0.24 + rnd() * 0.34;     // где разорвать ряд
    push(0.02, y, gap - 0.06, 0.055, false);
    push(gap + 0.02, y, 0.96 - gap, 0.055, false);
  }
  return out;
}

// ---------------------------------------------------------------------------
export class CityLights {
  constructor(quality) {
    this.q = quality;
    this.atlas = new Map();     // 'era|variant|class' → canvas (FRAME*STEPS × FRAME)
    this.pool = null;           // offscreen-слой пятен
    this.poolCtx = null;
    this.poolW = 0; this.poolH = 0; this.poolScale = 0.5;
    this.blob = new Map();      // 'warm'/'cold' → канвас градиента пятна
    this.on = false;            // слой работает в этом кадре
    this.hasPool = false;       // в слое пятен есть что показывать
    this.seed = 0;
    this.night = 0;
    this.bias = 0;
    this.time = 0;
    this.wl = WEATHER_DEFAULT;
    this.maxWindows = 0;
    this.bakesLeft = 0;
    // Заявки на окна: сначала копятся (note вызывается вперемешку с отрисовкой
    // зданий), потом выливаются одним проходом. Иначе на каждое окно пришлось
    // бы переключать globalCompositeOperation — а это сброс состояния контекста
    // 150 раз за кадр. Объекты переиспользуются: аллокация 150 литералов в
    // кадре — это 9000 объектов в секунду на ровном месте.
    this.win = [];
    this.winN = 0;
    this.stat = { pools: 0, windows: 0, bakes: 0 };
  }

  setQuality(q) {
    this.q = q;
    // Атласы от пресета не зависят (узор и цвет — функция эпохи), поэтому не
    // чистим: смена качества и так стоит перепечки всех спрайтов зданий, и
    // добавлять к ней ещё 30 выпечек незачем. Слой пятен пересоздастся сам,
    // если поменялось разрешение холста.
    this.trimCaches();
  }

  // -------------------------------------------------------------------
  // Готовит кадр: решает, работает ли слой вообще, и печёт слой пятен.
  // Вызывается ДО прохода по зданиям — пятна лежат на земле, здания должны
  // накрывать их, а не наоборот.
  //
  // opts: { zoom, time }. time — это renderer.this.time (секунды с запуска),
  // нужен только для мерцания костров; на sim.dayTime мерцание не сделать,
  // сутки идут слишком медленно.
  begin(sim, ox, oy, z, cw, ch, L, opts) {
    this.on = false;
    this.hasPool = false;
    this.winN = 0;
    this.stat.pools = 0; this.stat.windows = 0; this.stat.bakes = 0;
    this.bakesLeft = BAKES_PER_FRAME;
    if (!sim || !L) return;

    // Днём слой не стоит ничего: 0,03 — тот же порог, по которому renderer
    // решает не блитить карты свечения (иначе платим за невидимое).
    this.night = L.glow;
    if (this.night <= 0.03) return;

    const zoom = z / TILE_PX;
    const lod = lodForZoom(this.q, zoom);
    // Ниже порога свечения постройка занимает десяток пикселей: узор окон
    // превращается в один светлый пиксель, а пятно на земле — в кляксу
    // размером с квартал. Дешевле и честнее не рисовать ничего.
    if (!lod.buildingGlow) return;

    this.on = true;
    // Мир без сида (заглушка в тестах) не должен обнулять хеш: с seed = 0
    // все постройки получили бы соседние значения смесителя и зажглись бы
    // почти одновременно — ровно то, от чего мы уходим.
    this.seed = ((sim.world && sim.world.seed) | 0) || 0x1e5ca7e;
    this.bias = phaseBias(sim.dayTime);
    this.time = (opts && opts.time) || 0;
    this.wl = WEATHER_LIGHT[sim.weather] || WEATHER_DEFAULT;
    this.maxWindows = Math.min(lod.maxBuildings, 260);

    // На eco слоя пятен нет вовсе. Причина конкретная: полноэкранный блит в
    // 'lighter' — самая дорогая операция всего модуля (~0,5 мс на 1280×720
    // программного растеризатора), а eco целится в телефон, где этот бюджет
    // уже расписан. Окна на фасадах остаются — они и так почти бесплатны.
    if (this.q.detail < 1) return;

    this.ensurePool(cw, ch);
    if (!this.poolCtx) return;

    const pc = this.poolCtx;
    const s = this.poolScale;
    pc.setTransform(1, 0, 0, 1, 0, 0);
    pc.clearRect(0, 0, this.poolW, this.poolH);
    pc.globalCompositeOperation = 'lighter';

    // Потолок пятен ниже потолка окон: пятно — это блит градиента размером
    // с полтора тайла, окно — блит 40×40. На high это 160 против 200.
    const cap = Math.min(lod.maxBuildings, 160);
    const list = this.collect(sim, ox, oy, z, cw, ch, cap);

    const warmBlob = this.blobSprite(true);
    const coldBlob = this.blobSprite(false);
    if (!warmBlob || !coldBlob) return;
    for (let i = 0; i < list.length; i++) {
      const it = list[i];
      // Радиус: полтора габарита постройки плюс полтора тайла. Меньше —
      // пятно прячется под самим зданием и его не видно; больше — соседние
      // пятна сливаются в одно светлое поле и город теряет структуру.
      const r = (it.size * 0.75 + z * 1.5) * (0.55 + 0.45 * it.fill) * this.wl.radius * s;
      const cx = (it.sx + it.size / 2) * s;
      // Центр пятна не в центре здания, а чуть ниже: свет из окон падает на
      // землю ПЕРЕД домом, за домом его закрывает сам дом.
      const cy = (it.sy + it.size * 0.82) * s;
      pc.globalAlpha = clamp01(0.28 * it.fill * this.wl.pool);
      const blob = it.warm ? warmBlob : coldBlob;
      pc.drawImage(blob, cx - r, cy - r, r * 2, r * 2);
    }
    pc.globalAlpha = 1;
    pc.globalCompositeOperation = 'source-over';
    this.stat.pools = list.length;
    this.hasPool = list.length > 0;
  }

  // Собирает освещённые постройки в кадре. Отдельный метод, потому что тут
  // единственное место, где может понадобиться сортировка, и её хочется
  // держать на виду.
  collect(sim, ox, oy, z, cw, ch, cap) {
    const out = [];
    const bl = sim.buildings || [];
    for (let i = 0; i < bl.length; i++) {
      const b = bl[i];
      if (b.destroyed || !b.done) continue;   // в недострое никто не живёт
      const size = (b.size || 1) * z;
      const sx = ox + b.x * z, sy = oy + b.y * z;
      // Отсечение с запасом в полтора тайла: пятно у постройки за краем
      // экрана всё ещё светит внутрь кадра.
      const m = size + z * 1.5;
      if (sx < -m || sy < -m || sx > cw + m || sy > ch + m) continue;
      const fill = litFill(this.seed, b.x, b.y, this.night, this.bias);
      if (fill <= 0.02) continue;
      const own = BUILDING_ERA_IDX[b.id] || 0;
      // Та же формула, что в renderer.drawBuilding: постройка тянется к
      // текущей эпохе, но не дальше трёх ступеней от собственной.
      const era = Math.max(own, Math.min(9, Math.min(sim.eraIndex | 0, own + 3)));
      out.push({ sx, sy, size, fill, warm: warmEra(era) });
    }
    if (out.length > cap) {
      // Срабатывает редко (потолок 160 против типичных 40-120 построек в
      // кадре), поэтому сортировка здесь дешевле, чем постоянная поддержка
      // отсортированного списка. Оставляем ближние к центру экрана: они и
      // крупнее, и на них смотрят.
      const mx = cw / 2, my = ch / 2;
      out.sort((p, q) => ((p.sx - mx) ** 2 + (p.sy - my) ** 2) - ((q.sx - mx) ** 2 + (q.sy - my) ** 2));
      out.length = cap;
    }
    return out;
  }

  // Блит слоя пятен. Ставится ПЕРЕД проходом по зданиям.
  drawGround(ctx) {
    if (!this.on || !this.hasPool || !this.pool) return;
    ctx.save();
    ctx.globalCompositeOperation = 'lighter';
    // Ночная сила: чем темнее, тем заметнее пятна. Верхний предел 0,85, а не
    // 1: при единице земля под фонарём уходит в белое и теряет цвет травы.
    ctx.globalAlpha = clamp01(this.night) * 0.85;
    ctx.drawImage(this.pool, 0, 0, this.poolW, this.poolH,
      0, 0, this.poolW / this.poolScale, this.poolH / this.poolScale);
    ctx.restore();
  }

  // -------------------------------------------------------------------
  // Заявка на окна одной постройки. Вызывается из drawBuilding с тем же
  // прямоугольником, в который лёг спрайт (нарисованный или процедурный) —
  // модулю всё равно, какой именно.
  note(b, dx, dy, dw, dh, era) {
    if (!this.on || this.winN >= this.maxWindows) return;
    if (!(dw > 0) || !(dh > 0)) return;
    const fill = litFill(this.seed, b.x, b.y, this.night, this.bias);
    // 0,02 — тот же отсев, что в collect(): при заполнении в два процента
    // окно даёт прозрачность 0,02 на 40 пикселях, то есть ничего, а блит
    // стоит столько же, сколько полностью освещённый дом.
    if (fill <= 0.02) return;
    const k = frameIndex(fill);
    if (k <= 0) return;

    const e = Math.max(0, Math.min(9, era | 0));
    const cls = windowClass(e);
    const variant = (hashB(this.seed, b.x, b.y, 2) * VARIANTS) | 0;
    const at = this.atlasFor(e, variant, cls);
    if (!at) return;             // бюджет выпечки на кадр исчерпан

    // Мерцание — только у открытого огня и только там, где есть запас
    // (detail >= 1). Фаза своя у каждого костра, иначе весь лагерь дышит в
    // такт и это сразу читается как машина. 5,7 рад/с — примерно один цикл
    // за секунду, живое пламя дрожит быстрее, но на экране быстрее уже рябь.
    let a = fill * this.wl.win;
    if (cls === 'fire' && this.q.detail >= 1) {
      const ph = hashB(this.seed, b.x, b.y, 3) * 6.283;
      a *= 0.80 + 0.20 * (0.5 + 0.5 * Math.sin(this.time * 5.7 + ph));
    }

    const r = facadeRect(dx, dy, dw, dh);
    let rec = this.win[this.winN];
    if (!rec) rec = this.win[this.winN] = { at: null, k: 0, x: 0, y: 0, w: 0, h: 0, a: 0 };
    rec.at = at; rec.k = k;
    rec.x = r.x; rec.y = r.y; rec.w = r.w; rec.h = r.h;
    rec.a = clamp01(a);
    this.winN++;
  }

  // Выливает все заявки. Ставится ПОСЛЕ прохода по зданиям — ровно там же,
  // где renderer выливает свой _pendingGlow, и по той же причине: одно
  // переключение режима наложения на весь город вместо ста пятидесяти.
  drawWindows(ctx) {
    if (!this.on || !this.winN) return;
    ctx.save();
    ctx.globalCompositeOperation = 'lighter';
    // Общий множитель ночи: вечером в полсилы окна должны и светить в
    // полсилы, иначе сумерки выглядят ярче полуночи.
    const nk = clamp01(this.night);
    for (let i = 0; i < this.winN; i++) {
      const w = this.win[i];
      ctx.globalAlpha = w.a * nk;
      ctx.drawImage(w.at, w.k * FRAME - FRAME, 0, FRAME, FRAME, w.x, w.y, w.w, w.h);
    }
    ctx.restore();
    this.stat.windows = this.winN;
  }

  stats() { return { ...this.stat, atlases: this.atlas.size, on: this.on }; }

  // -------------------------------------------------------------------
  // Слой пятен. Половинное разрешение: пятно — это плавный градиент без
  // единой резкой границы, на нём половинное разрешение не отличить от
  // полного, а закраска и очистка стоят вчетверо дешевле.
  ensurePool(cw, ch) {
    const w = Math.max(1, Math.round(cw * this.poolScale));
    const h = Math.max(1, Math.round(ch * this.poolScale));
    if (this.pool && this.poolW === w && this.poolH === h) return;
    if (typeof document === 'undefined') return;
    this.pool = document.createElement('canvas');
    this.pool.width = w; this.pool.height = h;
    this.poolCtx = this.pool.getContext('2d');
    this.poolW = w; this.poolH = h;
  }

  // Круглое пятно света — ОДИН раз в offscreen, дальше только блит.
  // Спад не линейный: 0,45 на трети радиуса даёт «ядро под окном плюс
  // длинный хвост», линейный градиент читается как плоский диск.
  blobSprite(warm) {
    const key = warm ? 'warm' : 'cold';
    const have = this.blob.get(key);
    if (have) return have;
    if (typeof document === 'undefined') return null;
    const S = 96;   // блит всё равно идёт с ужатием, 96 хватает с запасом
    const cv = document.createElement('canvas');
    cv.width = S; cv.height = S;
    const c = cv.getContext('2d');
    const g = c.createRadialGradient(S / 2, S / 2, 0, S / 2, S / 2, S / 2);
    const col = warm ? '255,182,96' : '150,214,255';
    g.addColorStop(0, `rgba(${col},0.90)`);
    g.addColorStop(0.33, `rgba(${col},0.45)`);
    g.addColorStop(0.70, `rgba(${col},0.13)`);
    g.addColorStop(1, `rgba(${col},0)`);
    c.fillStyle = g;
    c.fillRect(0, 0, S, S);
    this.blob.set(key, cv);
    return cv;
  }

  // -------------------------------------------------------------------
  // Атлас узора окон: STEPS кадров FRAME×FRAME подряд по горизонтали.
  // Кадр k (нумерация с 1) содержит окна с rank < k/STEPS, то есть кадры
  // вложены друг в друга — уже зажжённое окно не гаснет при переходе к
  // следующему кадру.
  atlasFor(era, variant, cls) {
    const key = `${era}|${variant}|${cls}`;
    const have = this.atlas.get(key);
    if (have) {
      // «Трогаем» запись: Map хранит порядок вставки, и это делает prune
      // настоящим LRU, а не «выкинь самое старое по времени создания».
      this.atlas.delete(key); this.atlas.set(key, have);
      return have;
    }
    if (this.bakesLeft <= 0 || typeof document === 'undefined') return null;
    this.bakesLeft--;
    this.stat.bakes++;
    const cv = this.bakeAtlas(era, variant, cls);
    this.atlas.set(key, cv);
    this.trimCaches();
    return cv;
  }

  bakeAtlas(era, variant, cls) {
    const cv = document.createElement('canvas');
    cv.width = FRAME * STEPS; cv.height = FRAME;
    const c = cv.getContext('2d');
    const pal = ERA_PALETTE[Math.max(0, Math.min(9, era))];
    const rgb = hex2rgb(pal.glow);
    const core = `rgb(${rgb[0]},${rgb[1]},${rgb[2]})`;
    const wins = layoutWindows(cls, variant);

    // Размытие делаем ЗДЕСЬ и только здесь. В кадре ctx.filter/shadowBlur —
    // это то, что в своё время уронило город с 60 FPS до девяти (см.
    // renderer.glowSprite); в выпечке, которая случается один раз на эпоху,
    // те же 0,05 мс никого не волнуют, зато окно получает ореол и перестаёт
    // выглядеть наклейкой поверх стены.
    c.shadowColor = `rgba(${rgb[0]},${rgb[1]},${rgb[2]},0.85)`;

    for (let k = 1; k <= STEPS; k++) {
      const ox = (k - 1) * FRAME;
      const thr = k / STEPS;
      for (let i = 0; i < wins.length; i++) {
        const w = wins[i];
        if (w.rank >= thr) continue;
        const x = ox + w.x * FRAME, y = w.y * FRAME;
        const ww = Math.max(1, w.w * FRAME), hh = Math.max(1, w.h * FRAME);
        if (w.soft) {
          // Огонь: не прямоугольник, а мягкое пятно. Радиальный градиент
          // прямо здесь — он всё равно печётся один раз.
          const g = c.createRadialGradient(x + ww / 2, y + hh / 2, 0, x + ww / 2, y + hh / 2, ww);
          g.addColorStop(0, `rgba(${rgb[0]},${rgb[1]},${rgb[2]},1)`);
          g.addColorStop(0.45, `rgba(${rgb[0]},${rgb[1]},${rgb[2]},0.42)`);
          g.addColorStop(1, `rgba(${rgb[0]},${rgb[1]},${rgb[2]},0)`);
          c.shadowBlur = 0;
          c.fillStyle = g;
          c.fillRect(x - ww / 2, y - hh / 2, ww * 2, hh * 2);
        } else {
          c.shadowBlur = FRAME * 0.06;   // ~3 px — ореол в полокна
          c.fillStyle = core;
          c.fillRect(x, y, ww, hh);
        }
      }
    }
    return cv;
  }

  // Потолки кэшей берём из пресета. Атласы мелкие (48*288*4 ≈ 55 КБ), но
  // при живой игре через десять эпох их набирается тридцать, и без потолка
  // это единственная в модуле утечка, которая копится молча.
  trimCaches() {
    const caps = (this.q && this.q.caps) || {};
    prune(this.atlas, {
      maxEntries: Math.max(6, Math.round((caps.spriteEntries || 80) / 4)),
      maxBytes: Math.max(1, (caps.spriteMB || 18)) * 1024 * 1024 * 0.08,
      bytesOf: canvasBytes,
    });
  }
}

