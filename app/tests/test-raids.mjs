// Тесты ритма набегов. Запуск: node app/tests/test-raids.mjs
//
// ЗАЧЕМ ЭТОТ НАБОР СУЩЕСТВУЕТ. Здесь ловится не «работает ли функция», а
// поведение игры целиком: набеги обязаны приходить редко и с перерывом. В
// проекте уже был случай, когда они шли ПОДРЯД каждый день (51, 52, 53, 54…),
// и поселение из двадцати двух человек вымирало до одного за полсотни дней —
// двадцать три смерти из двадцати трёх были рейдами. Ни один существующий тест
// этого не заметил: все модули по отдельности вели себя правильно, ломался
// стык между ядром (tickRaids) и wire_army (resolveRaidParty), где проверка
// «ядро уже разыграло волну» сравнивалась с sim.day, хотя wire_army вызывается
// РАНЬШЕ tickRaids в тех же сутках, и равенство не выполнялось никогда.
//
// Поэтому проверки здесь идут по живой партии, а не по подделке: только так
// виден порядок вызовов, который и был сломан.
import { Simulation } from '../src/core/simulation.js';

let pass = 0, fail = 0;
const t = (name, fn) => { try { fn(); pass++; console.log('OK ', name); } catch (e) { fail++; console.log('FAIL', name, '—', e.message); } };
const ok = (cond, msg) => { if (!cond) throw new Error(msg); };

// Прогон партии без игрока с записью дней, когда набег дошёл до поселения.
function runRaids(seed, era, days) {
  const sim = new Simulation(seed, { startEra: era });
  const hits = [];
  let seen = 0;
  for (let d = 1; d <= days; d++) {
    sim.tick(1);
    for (const l of sim.log.slice(seen)) {
      if (/Рейд .* прорвался/.test(l.text || '')) hits.push(d);
    }
    seen = sim.log.length;
  }
  const gaps = hits.slice(1).map((h, i) => h - hits[i]);
  return { sim, hits, gaps };
}

console.log('--- Ритм набегов ---');
{
  const { hits, gaps } = runRaids(11, 5, 300);

  t('набеги вообще приходят (иначе тест ничего не охраняет)',
    () => ok(hits.length >= 2, `за 300 дней их ${hits.length}`));

  // Главная проверка. Ядро назначает следующий набег через rng.int(40, 70);
  // всё, что чаще, означает, что таймер кто-то продавливает.
  t('между набегами не меньше 30 дней',
    () => {
      const bad = gaps.filter(g => g < 30);
      ok(bad.length === 0, `слишком частые промежутки: ${bad.join(', ')} (все: ${gaps.join(', ')})`);
    });

  t('двух набегов в одни сутки не бывает',
    () => ok(new Set(hits).size === hits.length, `дни повторяются: ${hits.join(', ')}`));

  // Прямой перевод прежней поломки в число: 300 дней при промежутке 40–70
  // дают самое большее восемь волн. Пятнадцать означали бы возврат петли.
  t('за 300 дней не больше восьми набегов',
    () => ok(hits.length <= 8, `их ${hits.length}: ${hits.join(', ')}`));
}

console.log('\n--- Поселение переживает набеги ---');
{
  // Без игрока армия не строится, и это худший случай из честных. Держава
  // обязана поредеть, но не исчезнуть: набег ворует и убивает, а не стирает.
  const { sim } = runRaids(11, 5, 300);
  t('люди остались живы', () => ok(sim.villagers.length >= 3,
    `в живых ${sim.villagers.length}`));
  t('казна не обнулилась', () => ok(sim.res.gold > 50,
    `золота ${sim.res.gold.toFixed(0)}`));
}

console.log('\n--- Отряд набега не остаётся на карте навсегда ---');
{
  // Именно незакрытый отряд и крутил петлю: он снова и снова продавливал
  // таймер ядра в ноль.
  const sim = new Simulation(11, { startEra: 5 });
  let maxStreak = 0, streak = 0;
  for (let d = 1; d <= 200; d++) {
    sim.tick(1);
    const alive = sim.war && sim.war.raid && sim.war.raid.squadId ? 1 : 0;
    streak = alive ? streak + 1 : 0;
    maxStreak = Math.max(maxStreak, streak);
  }
  // Отряд идёт от края карты до поселения — это десятки дней. Но не сто:
  // столько он живёт только если его забыли распустить.
  t('отряд набега не живёт на карте больше 60 дней подряд',
    () => ok(maxStreak <= 60, `самая длинная жизнь отряда — ${maxStreak} дн.`));
}

console.log(`\n=== ${pass} OK / ${fail} FAIL ===`);
if (fail) process.exit(1);
